#!/usr/bin/env python3
"""
E2E Test: Complete Galaxy Workflow Execution Pipeline

This test validates the COMPLETE Galaxy workflow lifecycle:
1. Send user query to /api/chat/execute
2. Workflow is generated by AI
3. Workflow is saved to Galaxy
4. Workflow is invoked
5. Execution is polled until complete
6. Outputs are retrieved

NO FALLBACKS ALLOWED - Galaxy must work end-to-end.
"""

import os
import sys
import json
import time
import requests
from datetime import datetime

# Configuration
FRONTEND_URL = os.environ.get("FRONTEND_URL", "http://localhost:5000")
TIMEOUT_SECONDS = 180  # 3 minutes for complete pipeline

def print_header(msg: str):
    """Print a formatted header."""
    print(f"\n{'='*60}")
    print(f"  {msg}")
    print(f"{'='*60}")

def print_step(step: int, msg: str):
    """Print a step indicator."""
    print(f"\n[Step {step}] {msg}")

def test_galaxy_pipeline():
    """Test the complete Galaxy workflow execution pipeline."""

    print_header("E2E Test: Complete Galaxy Workflow Execution Pipeline")
    print(f"Frontend URL: {FRONTEND_URL}")
    print(f"Timeout: {TIMEOUT_SECONDS} seconds")
    print(f"Timestamp: {datetime.now().isoformat()}")

    # Step 1: Check frontend health
    print_step(1, "Checking frontend health...")
    try:
        health_resp = requests.get(f"{FRONTEND_URL}/api/health", timeout=10)
        if health_resp.status_code == 200:
            print("✅ Frontend is healthy")
        else:
            print(f"❌ Frontend health check failed: {health_resp.status_code}")
            return False
    except Exception as e:
        print(f"❌ Frontend connection failed: {e}")
        return False

    # Step 2: Send research query to /api/chat/execute
    print_step(2, "Sending research query to complete execution pipeline...")

    # Use a clear bioinformatics query that should trigger workflow generation
    research_query = "Create a workflow to analyze RNA-seq data with quality control and alignment"

    print(f"Query: {research_query}")

    try:
        start_time = time.time()
        response = requests.post(
            f"{FRONTEND_URL}/api/chat/execute",
            json={
                "message": research_query,
                "timeout_seconds": TIMEOUT_SECONDS
            },
            timeout=TIMEOUT_SECONDS + 30  # Extra buffer for HTTP timeout
        )
        execution_time = time.time() - start_time

        print(f"Response status: {response.status_code}")
        print(f"Execution time: {execution_time:.2f} seconds")

        if response.status_code != 200:
            print(f"❌ Pipeline request failed with status {response.status_code}")
            print(f"Response: {response.text[:500]}")
            return False

        result = response.json()

    except requests.exceptions.Timeout:
        print(f"❌ Request timed out after {TIMEOUT_SECONDS} seconds")
        return False
    except Exception as e:
        print(f"❌ Request failed: {e}")
        return False

    # Step 3: Validate pipeline result
    print_step(3, "Validating pipeline result...")

    print(f"Success: {result.get('success')}")
    print(f"Stage: {result.get('stage')}")
    print(f"Execution time: {result.get('execution_time_ms')} ms")

    if not result.get('success'):
        print(f"❌ Pipeline failed at stage: {result.get('stage')}")
        print(f"Error: {result.get('error')}")
        print(f"Full result: {json.dumps(result, indent=2)[:1000]}")
        return False

    # Step 4: Check workflow details
    print_step(4, "Checking workflow details...")

    workflow = result.get('workflow', {})
    invocation = result.get('invocation', {})
    outputs = result.get('outputs', [])
    metadata = result.get('metadata', {})

    print(f"Workflow ID: {workflow.get('id')}")
    print(f"Workflow name: {workflow.get('name')}")
    print(f"Workflow source: {workflow.get('source')}")
    print(f"Confidence: {workflow.get('confidence')}")

    print(f"\nInvocation ID: {invocation.get('id')}")
    print(f"Invocation state: {invocation.get('state')}")
    print(f"History ID: {invocation.get('history_id')}")

    print(f"\nOutputs: {len(outputs)} datasets")
    for output in outputs[:5]:  # Show first 5 outputs
        print(f"  - {output.get('name')} ({output.get('extension')}, {output.get('state')})")

    print(f"\nMetadata:")
    print(f"  Tools used: {metadata.get('tools_used')}")
    print(f"  Datasets assigned: {metadata.get('datasets_assigned')}")
    print(f"  Steps count: {metadata.get('steps_count')}")

    # Step 5: Verify execution completed
    print_step(5, "Verifying execution completed...")

    final_state = invocation.get('state', 'unknown')

    if final_state in ['ok', 'scheduled']:
        print(f"✅ Workflow execution completed successfully (state: {final_state})")
    else:
        print(f"⚠️ Workflow execution state: {final_state}")

    # Step 6: Check assistant response
    print_step(6, "Checking assistant response...")

    assistant_response = result.get('response', '')
    suggestions = result.get('suggestions', [])

    print(f"Response preview: {assistant_response[:300]}...")
    print(f"Suggestions: {suggestions[:3]}")

    # Final verdict
    print_header("TEST RESULT")

    if result.get('success') and workflow.get('id') and invocation.get('id'):
        print("✅ PASSED: Complete Galaxy workflow execution pipeline works!")
        print(f"\n📊 Summary:")
        print(f"   - Workflow generated: {workflow.get('name')}")
        print(f"   - Workflow saved to Galaxy: ID {workflow.get('id')}")
        print(f"   - Workflow invoked: Invocation ID {invocation.get('id')}")
        print(f"   - Final state: {final_state}")
        print(f"   - Outputs: {len(outputs)} datasets")
        print(f"   - Total time: {result.get('execution_time_ms', 0) / 1000:.2f} seconds")
        return True
    else:
        print("❌ FAILED: Galaxy workflow execution pipeline incomplete")
        print(f"Missing: workflow_id={bool(workflow.get('id'))}, invocation_id={bool(invocation.get('id'))}")
        return False


def main():
    """Run the test."""
    success = test_galaxy_pipeline()

    if success:
        print("\n✅ All tests passed!")
        sys.exit(0)
    else:
        print("\n❌ Tests failed!")
        sys.exit(1)


if __name__ == "__main__":
    main()
