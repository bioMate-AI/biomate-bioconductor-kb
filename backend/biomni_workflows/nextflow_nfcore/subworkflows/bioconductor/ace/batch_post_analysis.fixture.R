# [biomate-fx-deps] self-install the fixture's declared packages (real example data) on a clean runtime
.fx_deps <- c("ACE")
.fx_miss <- .fx_deps[!vapply(.fx_deps, function(.p) requireNamespace(.p, quietly=TRUE), logical(1))]
if (length(.fx_miss)) {
  if (!requireNamespace("BiocManager", quietly=TRUE)) install.packages("BiocManager", repos="https://cloud.r-project.org")
  bin <- tryCatch(sprintf("https://bioconductor.org/packages/%s/container-binaries/bioconductor_docker", BiocManager::version()), error=function(e) NULL)
  suppressMessages(tryCatch(BiocManager::install(.fx_miss, update=FALSE, ask=FALSE, site_repository=bin), error=function(e) BiocManager::install(.fx_miss, update=FALSE, ask=FALSE)))
}
library(ACE)

# 1. Reproduce the VIGNETTE'S OWN data-preparation code
# The vignette uses `data("copyNumbersSegmented")` to load the example segmented QDNAseq object.
data("copyNumbersSegmented")

# 2. Serialize that object to EACH declared input file

# Input file 1: Segmented QDNAseq object
# The workflow reads a "Segmented QDNAseq object". The vignette demonstrates
# using `copyNumbersSegmented.rds` as an input for `runACE` when `filetype='rds'`.
# The `copyNumbersSegmented` object is an S4 object (QDNAseqCopyNumbers),
# so `saveRDS` is the appropriate serialization method.
saveRDS(copyNumbersSegmented, "copyNumbersSegmented.rds")

# Input file 2: models.tsv
# The vignette describes `fitpicker.tsv` as an output file generated by `runACE`
# that contains sample names and cellularities, and is used for model selection.
# Since the prompt specifies `models.tsv` as an input file for the workflow,
# we create a minimal, plausible tab-separated file based on the vignette's description
# of `fitpicker.tsv`. It should contain sample names from the QDNAseq object.
sample_names <- sampleNames(copyNumbersSegmented)
models_df <- data.frame(
  sample = sample_names,
  cellularity = c(0.79, 0.38), # Example cellularities from vignette section 2.4
  ploidy = c(2, 2),            # Example ploidies from vignette section 2.4
  likely_fit = c("lastminimum", "bestfit"), # Example fits from vignette section 2.4
  stringsAsFactors = FALSE
)

# Write the data frame to a tab-separated file.
write.table(models_df, "models.tsv", sep = "\t", row.names = FALSE, quote = FALSE)