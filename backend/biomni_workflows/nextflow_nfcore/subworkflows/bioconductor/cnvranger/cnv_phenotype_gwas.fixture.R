library(CNVRanger)
library(GenomicRanges)
library(RaggedExperiment)

# Reproduce the VIGNETTE'S OWN data-preparation code

# Set up data directory and read CNV calls
data.dir <- system.file("extdata", package="CNVRanger")
call.file <- file.path(data.dir, "Silva16_PONE_CNV_calls.csv")
calls <- read.csv(call.file, as.is=TRUE)

# Convert to GRangesList
grl <- GenomicRanges::makeGRangesListFromDataFrame(calls, split.field="NE_id", keep.extra.columns=TRUE)
grl <- GenomicRanges::sort(grl)

# Convert to RaggedExperiment
ra <- RaggedExperiment::RaggedExperiment(grl)

# Add simulated phenotype data to colData
set.seed(123) # For reproducibility of rnorm
weight <- rnorm(ncol(ra), mean=1100, sd=100)
fcr <- rnorm(ncol(ra), mean=6, sd=1.5)
RaggedExperiment::colData(ra)$weight <- round(weight, digits=2)
RaggedExperiment::colData(ra)$fcr <- round(fcr, digits=2)

# Serialize objects to declared input files

# CNVOut.txt: This will be the 'calls' data.frame.
# The vignette reads a CSV, so writing as CSV is appropriate.
write.csv(calls, "CNVOut.txt", row.names = FALSE, quote = FALSE)

# Pheno.txt: This will be the colData from the RaggedExperiment object.
# It's a DataFrame with sample IDs as row names, which are important.
pheno_data <- as.data.frame(RaggedExperiment::colData(ra))
write.csv(pheno_data, "Pheno.txt", row.names = TRUE, quote = FALSE)

# MapPenn.txt: This file is not directly generated by the vignette's data prep.
# However, the prompt requires it. The closest data available from the vignette
# that could represent "mapping" information (e.g., SNP positions) are the
# unique genomic coordinates from the 'calls' data. We extract unique
# chromosome and start positions, using their exact names from the 'calls' object.
map_data_for_penn <- unique(calls[, c("chr", "start")])
write.table(map_data_for_penn, "MapPenn.txt", sep = "\t", row.names = FALSE, quote = FALSE)