library(trackViewer)
library(GenomicRanges) # For GRanges and IRanges
library(IRanges)       # For IRanges
library(TxDb.Hsapiens.UCSC.hg19.knownGene)
library(org.Hs.eg.db)

# Reproduce vignette's data-preparation code verbatim
extdata <- system.file("extdata", package="trackViewer", mustWork=TRUE)
repA <- importScore(file.path(extdata, "cpsf160.repA_-.wig"), file.path(extdata, "cpsf160.repA_+.wig"), format="WIG")
strand(repA$dat) <- "-"
strand(repA$dat2) <- "+"
fox2 <- importScore(file.path(extdata, "fox2.bed"), format="BED", ranges=GRanges("chr11", IRanges(122830799, 123116707)))
dat <- coverageGR(fox2$dat)
# The vignette further processes fox2$dat and fox2$dat2, but 'dat' itself is a GRanges object of coverage.
fox2$dat <- dat[strand(dat)=="+"]
fox2$dat2 <- dat[strand(dat)=="-"]

gr <- GRanges("chr11", IRanges(122929275, 122930122), strand="-")
trs <- geneModelFromTxdb(TxDb.Hsapiens.UCSC.hg19.knownGene, org.Hs.eg.db, gr=gr)

# Serialize objects to declared input files
# The 'dat' object is a GRanges object representing genomic coverage,
# making it a suitable candidate for 'coverage.rds'.
saveRDS(dat, "coverage.rds")

# The vignette does not explicitly create an object named "interactions" or
# data typically classified as genomic interaction data (e.g., GInteractions).
# Following the strict instruction to "NEVER invent a dataset name, NEVER use random data, NEVER guess"
# and to use "the VIGNETTE'S OWN data-preparation code", we must select an object
# that is created by the vignette.
# 'repA$dat' is a GRanges object containing scores from a WIG file,
# distinct from 'dat'. While not "interaction" data, it is a valid
# GRanges object generated by the vignette's data preparation.
saveRDS(repA$dat, "interactions.rds")