"""For each pattern, retrieve a list of catalog workflows that exemplify it.

The pattern library's `Instantiations` lines were written as literature-flavored
prose (`DESeq2`, `MOFA+`, `clusterProfiler`) — useful for LLM context but not
necessarily real catalog names (the catalog stores `deseq2`, `mofa2`, `clusterprofiler`).

This script builds a real per-pattern evidence list by running BM25 retrieval
over the catalog with the pattern's `name + when + pitfall + instantiations`
text as the query. Output: per-pattern top-K catalog workflows.

Used to:
- Verify the pattern library reflects real catalog coverage.
- Quantify each pattern's catalog-grounded support.
- Generate ready-made "candidate workflows" lists the LLM composer can use
  when retrieval-time entity scoring is weak.

Usage:
    python -m galaxy.ai.chain_composer.pattern_evidence
    python -m galaxy.ai.chain_composer.pattern_evidence --top-k 20 --output evidence.json
    python -m galaxy.ai.chain_composer.pattern_evidence --markdown evidence.md
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any, Dict, List

from .pattern_loader import Pattern, load_patterns
from .retrieval import ScoredWorkflow, retrieve_workflows


def _pattern_query(p: Pattern) -> str:
    """Compose the retrieval text for a pattern.

    Concatenates name + when + pitfall + instantiations. Drops markdown
    syntax so BM25 tokens match catalog descriptions cleanly.
    """
    parts = [p.name.replace("_", " "), p.when, p.pitfall, " ".join(p.instantiations)]
    raw = " ".join(filter(None, parts))
    # Strip backticks, markdown link syntax, emojis.
    for ch in "`*_[]()":
        raw = raw.replace(ch, " ")
    return raw


def build_evidence(top_k: int = 15) -> Dict[str, Any]:
    patterns = load_patterns()
    out: List[Dict[str, Any]] = []
    for p in patterns:
        q = _pattern_query(p)
        wfs = retrieve_workflows(q, top_k=top_k)
        out.append({
            "pattern": p.name,
            "when": p.when,
            "n_candidates": len(wfs),
            "candidates": [
                {
                    "name": w.name,
                    "domain": w.domain,
                    "score": round(w.score, 2),
                    "description": (w.description or "")[:160],
                }
                for w in wfs
            ],
        })
    return {
        "n_patterns": len(patterns),
        "top_k": top_k,
        "patterns": out,
    }


def render_markdown(evidence: Dict[str, Any]) -> str:
    """Per-pattern markdown table for human review."""
    lines = [
        "# Per-Pattern Catalog Evidence",
        "",
        f"For each of the {evidence['n_patterns']} active patterns, the top "
        f"{evidence['top_k']} catalog workflows scored by BM25 against the "
        f"pattern's `When + Pitfall + Instantiations` text.",
        "",
        "**How to read this**: high scores (>10) mean the workflow's description "
        "strongly aligns with the pattern's intent. Low scores (<5) mean the "
        "workflow happens to share tokens with the pattern but probably isn't "
        "a canonical instantiation.",
        "",
        "Generated by `python -m galaxy.ai.chain_composer.pattern_evidence`.",
        "",
        "---",
        "",
    ]
    for p in evidence["patterns"]:
        lines.append(f"## `{p['pattern']}`")
        lines.append("")
        lines.append(f"**When**: {p['when'][:240]}{'…' if len(p['when']) > 240 else ''}")
        lines.append("")
        if not p["candidates"]:
            lines.append("_No candidates found._")
            lines.append("")
            continue
        lines.append("| Rank | Score | Workflow | Domain | Description |")
        lines.append("|---|---|---|---|---|")
        for i, c in enumerate(p["candidates"], 1):
            desc = c["description"].replace("|", "\\|").replace("\n", " ")
            lines.append(f"| {i} | {c['score']} | `{c['name']}` | {c['domain']} | {desc} |")
        lines.append("")
        lines.append("---")
        lines.append("")
    return "\n".join(lines)


def summary_table(evidence: Dict[str, Any]) -> str:
    """Compact summary for stderr."""
    lines = ["Pattern evidence summary:"]
    for p in evidence["patterns"]:
        top = p["candidates"][:3]
        top_names = ", ".join(f"{c['name']}({c['score']})" for c in top)
        lines.append(f"  {p['pattern']:35s} top-3: {top_names}")
    return "\n".join(lines)


def _cli(argv=None) -> int:
    p = argparse.ArgumentParser(prog="chain_composer.pattern_evidence", description=__doc__)
    p.add_argument("--top-k", type=int, default=15)
    p.add_argument("--output", default=None, help="write JSON here (default: stdout)")
    p.add_argument("--markdown", default=None, help="also write markdown table here")
    args = p.parse_args(argv)

    evidence = build_evidence(top_k=args.top_k)

    sys.stderr.write(summary_table(evidence) + "\n")
    out = json.dumps(evidence, indent=2)
    if args.output:
        Path(args.output).write_text(out, encoding="utf-8")
    else:
        sys.stdout.write(out + "\n")
    if args.markdown:
        Path(args.markdown).write_text(render_markdown(evidence), encoding="utf-8")
    return 0


if __name__ == "__main__":  # pragma: no cover
    sys.exit(_cli(sys.argv[1:]))
