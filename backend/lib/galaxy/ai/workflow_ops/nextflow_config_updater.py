"""
Nextflow 配置更新器

专门处理 Nextflow workflow 的配置和参数更新
"""

import logging
import re
from pathlib import Path
from typing import Dict, Any, List, Optional

log = logging.getLogger(__name__)


class NextflowConfigUpdater:
    """
    Nextflow 配置更新器

    支持：
    1. 添加/修改运行时参数（--param value）
    2. 更新 nextflow.config 文件
    3. 更新进程级别的资源配置
    4. 添加 skip 参数（如 --skip_filter_gtf）
    """

    def __init__(self, workflow_dir: Path):
        """
        Args:
            workflow_dir: Nextflow workflow 工作目录
        """
        self.workflow_dir = Path(workflow_dir)
        self.config_file = self.workflow_dir / "nextflow.config"
        self.params_file = self.workflow_dir / "ai_ops_params.json"

    def add_runtime_param(
        self,
        param_name: str,
        param_value: Any,
        param_type: str = 'auto'
    ) -> bool:
        """
        添加运行时参数

        Args:
            param_name: 参数名（如 skip_filter_gtf）
            param_value: 参数值
            param_type: 参数类型（boolean, string, number, auto）

        Returns:
            True if successful
        """
        try:
            # 参数会以 JSON 格式保存，在重启时作为 --params-file 传递
            import json

            # 读取现有参数
            if self.params_file.exists():
                with open(self.params_file, 'r') as f:
                    params = json.load(f)
            else:
                params = {}

            # 添加新参数
            params[param_name] = param_value

            # 保存
            with open(self.params_file, 'w') as f:
                json.dump(params, f, indent=2)

            log.info(f"✅ Added runtime param: {param_name} = {param_value}")
            return True

        except Exception as e:
            log.error(f"Failed to add runtime param {param_name}: {e}", exc_info=True)
            return False

    def update_process_config(
        self,
        process_name: str,
        config_key: str,
        config_value: Any
    ) -> bool:
        """
        更新进程级别的配置

        Example:
            update_process_config(
                'FILTER_GTF_BY_TRANSCRIPT',
                'memory',
                '16.GB'
            )

        这会在 nextflow.config 中添加：
        process {
            withName: FILTER_GTF_BY_TRANSCRIPT {
                memory = '16.GB'
            }
        }
        """
        try:
            # 读取现有配置
            if self.config_file.exists():
                with open(self.config_file, 'r') as f:
                    config_content = f.read()
            else:
                config_content = "// Auto-generated by AI Ops\n\n"

            # 检查是否已有 process 块
            if 'process {' not in config_content:
                config_content += "\nprocess {\n}\n"

            # 添加或更新进程配置
            process_config = f"""
    withName: '{process_name}' {{
        {config_key} = '{config_value}'
    }}
"""

            # 在 process 块中插入
            config_content = self._insert_into_process_block(
                config_content,
                process_config
            )

            # 写回文件
            with open(self.config_file, 'w') as f:
                f.write(config_content)

            log.info(f"✅ Updated process config: {process_name}.{config_key} = {config_value}")
            return True

        except Exception as e:
            log.error(f"Failed to update process config: {e}", exc_info=True)
            return False

    def add_skip_parameter(self, skip_param: str) -> bool:
        """
        添加 skip 参数（如 skip_filter_gtf）

        这是一个常用的快捷方法
        """
        return self.add_runtime_param(skip_param, True, 'boolean')

    def update_resource_limits(
        self,
        memory: Optional[str] = None,
        cpus: Optional[int] = None,
        time: Optional[str] = None
    ) -> bool:
        """
        更新全局资源限制

        Args:
            memory: 如 '16.GB'
            cpus: 如 8
            time: 如 '4.h'
        """
        try:
            updates = []

            if memory:
                updates.append(f"    memory = '{memory}'")
            if cpus:
                updates.append(f"    cpus = {cpus}")
            if time:
                updates.append(f"    time = '{time}'")

            if not updates:
                return True

            # 读取配置
            if self.config_file.exists():
                with open(self.config_file, 'r') as f:
                    config_content = f.read()
            else:
                config_content = ""

            # 添加全局资源配置
            resource_config = f"""
// AI Ops: Global resource limits
process {{
{chr(10).join(updates)}
}}
"""

            config_content += "\n" + resource_config

            # 写回
            with open(self.config_file, 'w') as f:
                f.write(config_content)

            log.info(f"✅ Updated resource limits: memory={memory}, cpus={cpus}, time={time}")
            return True

        except Exception as e:
            log.error(f"Failed to update resource limits: {e}", exc_info=True)
            return False

    def get_runtime_command_args(self) -> List[str]:
        """
        获取运行时命令参数

        Returns:
            参数列表，如 ['--skip_filter_gtf', 'true', '--params-file', 'ai_ops_params.json']
        """
        args = []

        # 如果有参数文件，添加 --params-file
        if self.params_file.exists():
            args.extend(['--params-file', str(self.params_file)])

        return args

    def backup_config(self) -> Optional[Path]:
        """备份当前配置"""
        try:
            if not self.config_file.exists():
                return None

            import shutil
            import time

            backup_file = self.workflow_dir / f"nextflow.config.backup.{int(time.time())}"
            shutil.copy2(self.config_file, backup_file)

            log.info(f"Backed up config to {backup_file}")
            return backup_file

        except Exception as e:
            log.error(f"Failed to backup config: {e}")
            return None

    def restore_config(self, backup_file: Path) -> bool:
        """从备份恢复配置"""
        try:
            if not backup_file.exists():
                return False

            import shutil
            shutil.copy2(backup_file, self.config_file)

            log.info(f"Restored config from {backup_file}")
            return True

        except Exception as e:
            log.error(f"Failed to restore config: {e}")
            return False

    def _insert_into_process_block(
        self,
        config_content: str,
        process_config: str
    ) -> str:
        """在 process 块中插入配置"""
        # 找到 process { ... } 块
        pattern = r'(process\s*\{)(.*?)(\})'
        match = re.search(pattern, config_content, re.DOTALL)

        if match:
            # 在 process 块中插入
            before = match.group(1)
            inside = match.group(2)
            after = match.group(3)

            new_inside = inside + "\n" + process_config

            return config_content[:match.start()] + before + new_inside + "\n" + after + config_content[match.end():]
        else:
            # 没有 process 块，创建一个
            return config_content + f"\nprocess {{\n{process_config}\n}}\n"


class NextflowCommandBuilder:
    """
    构建 Nextflow 运行命令

    根据修复方案生成完整的 Nextflow 命令行
    """

    def __init__(self, workflow_dir: Path, pipeline: str):
        """
        Args:
            workflow_dir: 工作目录
            pipeline: Pipeline 名称（如 'nf-core/clipseq'）
        """
        self.workflow_dir = workflow_dir
        self.pipeline = pipeline
        self.config_updater = NextflowConfigUpdater(workflow_dir)

    def build_command(
        self,
        input_params: Dict[str, Any],
        profile: str = 'docker,aws_batch',
        resume: bool = False
    ) -> List[str]:
        """
        构建完整的 Nextflow 命令

        Returns:
            命令参数列表
        """
        cmd = ['nextflow', 'run', self.pipeline]

        # 添加 profile
        cmd.extend(['-profile', profile])

        # 添加输入参数
        for key, value in input_params.items():
            # 处理布尔值
            if isinstance(value, bool):
                if value:
                    cmd.append(f'--{key}')
            else:
                cmd.extend([f'--{key}', str(value)])

        # 添加 AI Ops 生成的参数
        ai_ops_args = self.config_updater.get_runtime_command_args()
        cmd.extend(ai_ops_args)

        # 添加工作目录
        cmd.extend(['-work-dir', str(self.workflow_dir / 'work')])

        # Resume（如果需要）
        if resume:
            cmd.append('-resume')

        return cmd
