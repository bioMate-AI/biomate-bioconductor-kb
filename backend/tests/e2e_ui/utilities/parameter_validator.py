"""
Parameter Validator for E2E UI Tests

Validates LLM-generated parameters against expected values.
Checks confidence scores and parameter accuracy.
"""

from typing import List, Dict, Any, Optional, Set


class ParameterValidator:
    """
    Validate LLM-generated parameters from workflow generation.

    Validates:
    - Parameter values match expected
    - Confidence scores meet thresholds
    - Critical parameters are correct
    - Flexible parameters are within acceptable range
    """

    def __init__(self):
        """Initialize parameter validator."""
        self.validation_history = []

    def validate_generated_parameters(
        self,
        actual: List[Dict[str, Any]],
        expected: Dict[str, Dict[str, Any]],
        min_confidence: float = 0.6
    ) -> Dict[str, Any]:
        """
        Validate generated parameters against expected values.

        Args:
            actual: List of generated_parameters from API response
                [
                    {
                        "step_id": 0,
                        "tool_id": "biomate_dm_ensembl_genes",
                        "parameters": {"organism": "mouse", "filter": "kinase"},
                        "confidence": 0.85,
                        "reasoning": "..."
                    }
                ]
            expected: Dict mapping tool_id to expected parameter specs
                {
                    "biomate_dm_ensembl_genes": {
                        "expected_params": {"organism": "mouse"},
                        "critical_params": ["organism"],
                        "min_confidence": 0.75
                    }
                }
            min_confidence: Default minimum confidence threshold

        Returns:
            Validation results dictionary:
                {
                    "total_params": 2,
                    "passed": 1,
                    "failed": 1,
                    "low_confidence": 0,
                    "details": [...]
                }
        """
        results = {
            "total_params": len(actual),
            "passed": 0,
            "failed": 0,
            "low_confidence": 0,
            "confidence_sum": 0.0,
            "details": []
        }

        for param_set in actual:
            tool_id = param_set.get("tool_id", "unknown")
            actual_params = param_set.get("parameters", {})
            confidence = param_set.get("confidence", 0.0)
            reasoning = param_set.get("reasoning", "")

            # Get expected spec for this tool
            expected_spec = expected.get(tool_id, {})
            expected_params = expected_spec.get("expected_params", {})
            critical_params = expected_spec.get("critical_params", [])
            tool_min_conf = expected_spec.get("min_confidence", min_confidence)

            # Check confidence threshold
            confidence_ok = confidence >= tool_min_conf
            if not confidence_ok:
                results["low_confidence"] += 1

            results["confidence_sum"] += confidence

            # Compare parameters
            param_match = self._compare_parameters(
                actual=actual_params,
                expected=expected_params,
                critical_params=critical_params
            )

            # Determine pass/fail
            passed = param_match["all_critical_match"] and confidence_ok

            if passed:
                results["passed"] += 1
            else:
                results["failed"] += 1

            # Record details
            detail = {
                "tool_id": tool_id,
                "confidence": confidence,
                "confidence_ok": confidence_ok,
                "reasoning": reasoning,
                "expected": expected_params,
                "actual": actual_params,
                "critical_params": critical_params,
                "param_match": param_match,
                "passed": passed
            }
            results["details"].append(detail)

        # Calculate average confidence
        if results["total_params"] > 0:
            results["avg_confidence"] = results["confidence_sum"] / results["total_params"]
        else:
            results["avg_confidence"] = 0.0

        # Save to history
        self.validation_history.append(results)

        return results

    def _compare_parameters(
        self,
        actual: Dict[str, Any],
        expected: Dict[str, Any],
        critical_params: List[str]
    ) -> Dict[str, Any]:
        """
        Compare actual vs expected parameters.

        Args:
            actual: Actual parameters generated by LLM
            expected: Expected parameter values
            critical_params: List of parameter names that must match exactly

        Returns:
            Comparison results:
                {
                    "total_expected": 3,
                    "correct_count": 2,
                    "incorrect_count": 1,
                    "missing_count": 0,
                    "all_match": False,
                    "all_critical_match": True,
                    "details": {...}
                }
        """
        result = {
            "total_expected": len(expected),
            "correct_count": 0,
            "incorrect_count": 0,
            "missing_count": 0,
            "extra_count": 0,
            "all_match": False,
            "all_critical_match": True,
            "details": {}
        }

        # Check each expected parameter
        for param_name, expected_value in expected.items():
            is_critical = param_name in critical_params

            if param_name not in actual:
                result["missing_count"] += 1
                result["details"][param_name] = {
                    "status": "missing",
                    "expected": expected_value,
                    "actual": None,
                    "is_critical": is_critical,
                    "match": False
                }
                if is_critical:
                    result["all_critical_match"] = False
                continue

            actual_value = actual[param_name]

            # Compare values (with flexibility for numeric types)
            match = self._values_match(actual_value, expected_value, is_critical)

            if match:
                result["correct_count"] += 1
            else:
                result["incorrect_count"] += 1
                if is_critical:
                    result["all_critical_match"] = False

            result["details"][param_name] = {
                "status": "correct" if match else "incorrect",
                "expected": expected_value,
                "actual": actual_value,
                "is_critical": is_critical,
                "match": match
            }

        # Check for extra parameters not in expected
        for param_name in actual:
            if param_name not in expected:
                result["extra_count"] += 1

        # Determine if all parameters match
        result["all_match"] = (
            result["correct_count"] == result["total_expected"] and
            result["missing_count"] == 0
        )

        return result

    def _values_match(
        self,
        actual: Any,
        expected: Any,
        is_critical: bool
    ) -> bool:
        """
        Check if two values match, with flexibility for non-critical params.

        Args:
            actual: Actual value
            expected: Expected value
            is_critical: Whether this is a critical parameter

        Returns:
            True if values match (within tolerance for non-critical)
        """
        # Exact match
        if actual == expected:
            return True

        # String comparison (case-insensitive for some fields)
        if isinstance(actual, str) and isinstance(expected, str):
            # For critical params, exact match required
            if is_critical:
                return actual.lower() == expected.lower()
            # For non-critical, more flexible
            return actual.lower().strip() == expected.lower().strip()

        # Numeric comparison (allow ±20% for non-critical)
        if isinstance(actual, (int, float)) and isinstance(expected, (int, float)):
            if is_critical:
                return actual == expected
            else:
                # Allow 20% tolerance for non-critical numeric params
                tolerance = 0.2
                return abs(actual - expected) / max(abs(expected), 1) <= tolerance

        # List/array comparison
        if isinstance(actual, list) and isinstance(expected, list):
            if is_critical:
                return actual == expected
            else:
                # For non-critical, check if sets are similar
                return set(actual) == set(expected)

        # Default: must match exactly
        return False

    def validate_confidence_distribution(
        self,
        generated_parameters: List[Dict[str, Any]],
        expected_high_ratio: float = 0.5,
        expected_medium_ratio: float = 0.3
    ) -> Dict[str, Any]:
        """
        Validate the distribution of confidence scores.

        Args:
            generated_parameters: List of parameter sets with confidence scores
            expected_high_ratio: Expected % of high confidence (>= 0.8)
            expected_medium_ratio: Expected % of medium confidence (0.6-0.8)

        Returns:
            Distribution analysis results
        """
        total = len(generated_parameters)
        if total == 0:
            return {
                "total": 0,
                "high": 0,
                "medium": 0,
                "low": 0,
                "distribution_ok": False
            }

        high_count = sum(1 for p in generated_parameters if p.get("confidence", 0) >= 0.8)
        medium_count = sum(1 for p in generated_parameters if 0.6 <= p.get("confidence", 0) < 0.8)
        low_count = sum(1 for p in generated_parameters if p.get("confidence", 0) < 0.6)

        high_ratio = high_count / total
        medium_ratio = medium_count / total
        low_ratio = low_count / total

        # Check if distribution meets expectations
        distribution_ok = (
            high_ratio >= expected_high_ratio - 0.2 and  # Allow some flexibility
            low_ratio <= 0.2  # Low confidence should be rare
        )

        return {
            "total": total,
            "high": high_count,
            "medium": medium_count,
            "low": low_count,
            "high_ratio": high_ratio,
            "medium_ratio": medium_ratio,
            "low_ratio": low_ratio,
            "distribution_ok": distribution_ok,
            "meets_expectations": distribution_ok
        }

    def calculate_overall_accuracy(self) -> float:
        """
        Calculate overall parameter accuracy across all validations.

        Returns:
            Accuracy score (0-1) representing % of correct parameters
        """
        if not self.validation_history:
            return 0.0

        total_params = sum(v["total_params"] for v in self.validation_history)
        total_passed = sum(v["passed"] for v in self.validation_history)

        if total_params == 0:
            return 0.0

        return total_passed / total_params

    def get_summary(self) -> Dict[str, Any]:
        """
        Get summary of all validations performed.

        Returns:
            Summary statistics
        """
        if not self.validation_history:
            return {
                "total_validations": 0,
                "overall_accuracy": 0.0,
                "avg_confidence": 0.0
            }

        total_validations = len(self.validation_history)
        overall_accuracy = self.calculate_overall_accuracy()
        avg_confidence = sum(v["avg_confidence"] for v in self.validation_history) / total_validations

        return {
            "total_validations": total_validations,
            "overall_accuracy": overall_accuracy,
            "avg_confidence": avg_confidence,
            "total_params_checked": sum(v["total_params"] for v in self.validation_history),
            "total_passed": sum(v["passed"] for v in self.validation_history),
            "total_failed": sum(v["failed"] for v in self.validation_history),
            "total_low_confidence": sum(v["low_confidence"] for v in self.validation_history)
        }

    def __repr__(self):
        summary = self.get_summary()
        return (
            f"ParameterValidator("
            f"validations={summary['total_validations']}, "
            f"accuracy={summary['overall_accuracy']:.2%}, "
            f"avg_confidence={summary['avg_confidence']:.2f})"
        )
