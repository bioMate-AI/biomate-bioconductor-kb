class TestExperimentTypeClassification(unittest.TestCase):

    def _fcs_type(self, stem: str) -> str:
        """Helper: detect experiment type from a fake FCS path + tube name metadata."""
        from unittest.mock import MagicMock
        p = MagicMock()
        p.stem = stem
        p.parent.name = "flow-data"  # hyphen = non-word char → word boundaries fire
        p.suffix = ".fcs"
        # Pass tube_name in metadata so regex has another chance
        return detect_fcs_experiment_type(p, {"tube_name": stem, "experiment_name": stem, "channels": []})

    def test_cfse_classification(self):
        # Use hyphen-separated name so \bCFSE\b word boundary works
        t = self._fcs_type("CFSE-proliferation-d3")
        self.assertEqual(t, "cfse_proliferation")

    def test_cytokine_classification(self):
        # "cytokine" and "ICS" surrounded by word boundaries (\bICS\b requires non-word neighbours)
        t = self._fcs_type("CD4 cytokine ICS TNF")
        self.assertEqual(t, "cytokine_production")

    def test_qpcr_rt_classification(self):
        """RT-qPCR expression filename — hyphens give word boundaries."""
        pcrd = Path("/data/qpcr/RT-qPCR-mRNA-expression.csv")
        exp = detect_qpcr_experiment_type(pcrd, {"run_name": "RT-qPCR mRNA expression", "experiment_type": "", "targets": []})
        self.assertEqual(exp, "rt_qpcr_expression")

    def test_qpcr_crispr_classification(self):
        """CRISPR screen filename — hyphens give \bCRISPR\b word boundaries."""
        pcrd = Path("/data/qpcr/CRISPR-screen-sgRNA-indels.pcrd")
        exp = detect_qpcr_experiment_type(pcrd, {"run_name": "CRISPR screen sgRNA indels", "experiment_type": "", "targets": []})
        self.assertEqual(exp, "crispr_screen_qpcr")

    def test_plate_reader_protease_classification(self):
        """Trypsin kinetics → protease_kinetics.  Use space-separated assay_name."""
        csv_file = FIXTURES / "bmg_mars_export.csv"
        lines = _safe_read_lines(csv_file)
        vendor = detect_plate_reader_format(csv_file, lines)
        metadata = extract_plate_metadata(csv_file, vendor)
        # Use spaces so \btrypsin\b fires; path stem also uses spaces
        metadata["assay_name"] = "Trypsin kinetics 37C"
        t = detect_assay_type(Path("Trypsin kinetics 37C.csv"), metadata)
        self.assertEqual(t, "protease_kinetics")

    def test_plate_reader_ic50_classification(self):
        """MTT cell viability → cell_viability_ic50. Space-separated stem."""
        txt_file = FIXTURES / "gen5_kinetics.txt"
        lines = _safe_read_lines(txt_file)
        vendor = detect_plate_reader_format(txt_file, lines)
        metadata = extract_plate_metadata(txt_file, vendor)
        t = detect_assay_type(Path("IC50 erlotinib MTT.csv"), metadata)
        self.assertEqual(t, "cell_viability_ic50")


