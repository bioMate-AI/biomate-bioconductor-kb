REQUIRED_FIELDS = {"source", "workflow_id", "description", "message"}

class TestEventPayloadCompleteness(unittest.TestCase):

    def _assert_complete(self, event: dict, label: str):
        for field in REQUIRED_FIELDS:
            self.assertIn(field, event, f"[{label}] missing field: {field}")
            self.assertTrue(event[field], f"[{label}] field '{field}' is empty")
        # File path or directory
        has_location = bool(event.get("file_path") or event.get("directory") or event.get("fcs_dir"))
        self.assertTrue(has_location, f"[{label}] no file_path/directory/fcs_dir")

    def test_flow_cytometer_event(self):
        from backend.lib.integrations.flow_cytometer_connector import (
            FlowCytometerWatchedDir, FCSSample, read_fcs_header,
            detect_fcs_experiment_type, _WORKFLOW_MAP, _ANALYSIS_FUNCTION_MAP,
        )
        fcs = FIXTURES / "sample.fcs"
        meta = read_fcs_header(fcs)
        exp_type = detect_fcs_experiment_type(fcs, meta)
        workflow_id = _WORKFLOW_MAP.get(exp_type, "flow_cytometry_immunophenotyping")
        analysis_fn = _ANALYSIS_FUNCTION_MAP.get(exp_type, "")
        event = {
            "source": "flow_cytometer_watcher",
            "workflow_id": workflow_id,
            "experiment_type": exp_type,
            "directory": str(fcs.parent),
            "fcs_dir": str(fcs.parent),
            "file_count": 1,
            "analysis_function": analysis_fn,
            "description": f"Flow cytometry: 1 FCS files ({exp_type}). Cytometer: {meta.get('cytometer', 'unknown')}.",
            "message": f"New flow cytometry data: 1 FCS files ({exp_type}). Click to run analysis.",
        }
        self._assert_complete(event, "flow_cytometer")

    def test_plate_reader_event(self):
        csv_file = FIXTURES / "bmg_mars_export.csv"
        lines = _safe_read_lines(csv_file)
        vendor = detect_plate_reader_format(csv_file, lines)
        metadata = extract_plate_metadata(csv_file, vendor)
        assay_type = detect_assay_type(csv_file, metadata)
        from backend.lib.integrations.plate_reader_connector import _WORKFLOW_MAP, _ANALYSIS_FUNCTION_MAP
        workflow_id = _WORKFLOW_MAP.get(assay_type, "plate_reader_absorbance")
        analysis_fn = _ANALYSIS_FUNCTION_MAP.get(assay_type, "")
        event = {
            "source": "plate_reader_watcher",
            "workflow_id": workflow_id,
            "assay_type": assay_type,
            "file_path": str(csv_file),
            "directory": str(csv_file.parent),
            "analysis_function": analysis_fn,
            "description": f"Plate reader data: {assay_type} ({vendor}). BioMate analysis via {analysis_fn}.",
            "message": f"New plate reader data: {csv_file.name} ({assay_type}). Click to run analysis.",
        }
        self._assert_complete(event, "plate_reader")

    def test_qpcr_event(self):
        pcrd = FIXTURES / "cfx_run.pcrd"
        metadata = read_biorad_pcrd(pcrd)
        exp_type = detect_qpcr_experiment_type(pcrd, metadata)
        from backend.lib.integrations.qpcr_connector import _WORKFLOW_MAP, _ANALYSIS_FUNCTION_MAP
        workflow_id = _WORKFLOW_MAP.get(exp_type, "qpcr_differential_expression")
        analysis_fn = _ANALYSIS_FUNCTION_MAP.get(exp_type, "")
        event = {
            "source": "qpcr_watcher",
            "workflow_id": workflow_id,
            "experiment_type": exp_type,
            "file_path": str(pcrd),
            "directory": str(pcrd.parent),
            "analysis_function": analysis_fn,
            "description": f"qPCR run complete: {metadata.get('run_name', pcrd.stem)} ({exp_type}).",
            "message": f"New qPCR data: {pcrd.name} ({exp_type}). Click to run analysis.",
        }
        self._assert_complete(event, "qpcr")


