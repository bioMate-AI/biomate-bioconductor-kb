def read(p): return open(p, encoding="utf-8").read()


def section(text, start_pat, end_pat=None, include_end=False):
    """Lines from the first line matching start_pat up to (not incl.) the next line matching end_pat."""
    L = text.split("\n"); s = next(i for i, l in enumerate(L) if re.match(start_pat, l))
    e = len(L)
    if end_pat:
        for i in range(s + 1, len(L)):
            if re.match(end_pat, L[i]): e = i; break
    return "\n".join(L[s:e]).rstrip()


def cap(text, n):
    """Truncate at a paragraph boundary after at most n bytes; say so (the committee must know the excerpt is partial)."""
    b = text.encode()
    if len(b) <= n: return text
    cut = b[:n].decode(errors="ignore"); i = cut.rfind("\n\n")
    return cut[:i if i > n * 0.6 else len(cut)].rstrip() + "\n\n[... remainder of this section omitted from the packet for length; the full text is in the repository draft ...]"


def func(path, name, maxlines=None):
    src = read(path); tree = ast.parse(src); L = src.split("\n")
    for n in ast.walk(tree):
        if isinstance(n, (ast.FunctionDef, ast.ClassDef)) and n.name == name:
            a, b = n.lineno, n.end_lineno
            body = L[a - 1:b]
            if maxlines and len(body) > maxlines: body = body[:maxlines] + ["    # ... (excerpt truncated for the packet)"]
            rel = os.path.relpath(path, REPO)
            return f"### {rel} : {name} (line {a})\n```python\n" + "\n".join(body) + "\n```\n"
    raise SystemExit(f"function {name} not found in {path}")


def lines(path, a, b, lang="python"):
    L = read(path).split("\n")
    return f"### {os.path.relpath(path, REPO)} lines {a}-{b}\n```{lang}\n" + "\n".join(L[a - 1:b]) + "\n```\n"


