"""Generate a complete, reviewable DATA CATALOG of every on-prem-LLM training + test dataset:
location (local + S3), row count, schema, task/source breakdown, grader, and representative sample
instances per task. Output: a markdown doc + a samples_by_task.jsonl for deeper browsing.
"""
import argparse, json, collections, os, re

S3 = "s3://biomate-models-399683337364/biomate-core-local-trial/20260912"


def load(p):
    try:
        return [json.loads(l) for l in open(p) if l.strip()]
    except FileNotFoundError:
        return None


def clip(s, n=600):
    s = re.sub(r"\s+", " ", str(s or "")).strip()
    return s[:n] + (" …" if len(s) > n else "")


def msgs(r):
    return {m["role"]: m["content"] for m in r.get("messages", [])}


def sec_sft(f, path, s3, title, desc, per=4):
    rows = load(path)
    if rows is None:
        return f"\n## {title}\n\n_(not found: {path})_\n"
    tasks = collections.Counter(r.get("task", "?") for r in rows)
    srcs = collections.Counter(r.get("source", "?") for r in rows)
    out = [f"\n## {title}", f"\n{desc}", f"\n- **rows:** {len(rows):,}",
           f"- **local:** `{path}`", f"- **s3:** `{s3}`",
           f"- **schema:** `{list(rows[0].keys())}`",
           f"\n**Task distribution:** {dict(tasks.most_common())}",
           f"\n**Source distribution:** {dict(srcs.most_common(15))}\n"]
    by = collections.defaultdict(list)
    for r in rows:
        by[r.get("task", "?")].append(r)
    for t, rs in sorted(by.items(), key=lambda x: -len(x[1])):
        out.append(f"\n### sample — `{t}` ({len(rs):,} rows)\n")
        for r in rs[:per]:
            m = msgs(r)
            out.append(f"- **user:** {clip(m.get('user',''),500)}")
            out.append(f"  **assistant:** {clip(m.get('assistant',''),500)}\n")
    return "\n".join(out)


def sec_generic(path, s3, title, desc, fields, per=4):
    rows = load(path)
    if rows is None:
        return f"\n## {title}\n\n_(not found: {path})_\n"
    out = [f"\n## {title}", f"\n{desc}", f"\n- **rows:** {len(rows):,}",
           f"- **local:** `{path}`", f"- **s3:** `{s3}`",
           f"- **schema:** `{list(rows[0].keys())}`\n", "\n**Samples:**\n"]
    for r in rows[:per]:
        out.append("- " + " | ".join(f"**{k}:** {clip(r.get(k,''),300)}" for k in fields if k in r))
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    B = "/tmp/sftaudit"; D = "/Users/kky/biomate-review/docs/20260912_onprem_llm"
    parts = ["# On-prem LLM — complete data catalog (train + test)",
             "\n_Auto-generated by `build_data_catalog.py`. Every dataset with location, counts, schema, "
             "and sample instances for review. Canonical training file = `multitask_sft_enriched.jsonl`._\n",
             "\n## Index\n",
             "| dataset | split | rows | purpose |",
             "|---|---|---|---|",
             "| multitask_sft_enriched | TRAIN | 62,397 | active SFT set (all tasks) |",
             "| routing_openbook_sft | TRAIN (new) | 2,975 | open-book candidate-grounded routing |",
             "| routing_dpo_pairs_v2 | TRAIN (new) | 5,950 | contrastive DPO hard-negative pairs |",
             "| qa_gold | TRAIN (component) | 25,000 | gold biomedical MCQA (PubMedQA/MedMCQA/MedQA/SciQ) |",
             "| claude_decomp | TRAIN (component) | 8,428 | task-decomposition from claude logs |",
             "| latch_traj | TRAIN (component) | 132 | Latch agent trajectories |",
             "| gold_routing_eval | TEST | 279 | curated routing accept-set (clean gold) |",
             "| realbio_routing_eval | TEST | 199 | RealBio routing |",
             "| dbtest_routing_eval | TEST | 78 | dbtest routing |",
             "| corpus_eval_big | TEST | 8,110 | broad multi-task eval (⚠ generator-made) |",
             "| removal_eval | TEST | 149 | out-of-catalog composition |",
             ]
    # TRAIN
    parts.append(sec_sft("enriched", f"{B}/sft_train.jsonl", f"{S3}/sft/multitask_sft_enriched.jsonl",
                         "TRAIN — multitask_sft_enriched (CANONICAL active SFT)",
                         "The set actually used to train the SFT adapter. 17 tasks.", per=4))
    parts.append(sec_sft("ob", f"{B}/routing_openbook_sft.jsonl", f"{S3}/sft/routing_openbook_sft.jsonl",
                         "TRAIN — routing_openbook_sft (NEW, contrastive rebuild)",
                         "Open-book candidate-grounded routing: prompt = request + retrieved candidates; "
                         "target = exact gold copied from the list. Future-proof to catalog upgrades.", per=3))
    parts.append(sec_generic(f"{B}/routing_dpo_pairs_v2.jsonl", f"{S3}/sft/routing_dpo_pairs_v2.jsonl",
                             "TRAIN — routing_dpo_pairs_v2 (NEW, contrastive)",
                             "Hard-negative DPO pairs. `chosen`=gold; `rejected`= semi-hard same-domain sibling "
                             "or off-catalog name. Deterministic, zero-LLM.",
                             ["task", "chosen", "rejected", "prompt"], per=6))
    parts.append(sec_sft("qa", f"{B}/qa_gold.jsonl", f"{S3}/sft/qa_gold.jsonl",
                         "TRAIN component — qa_gold", "Gold biomedical MCQA adopted from public sets.", per=3))
    parts.append(sec_sft("decomp", f"{B}/claude_decomp.jsonl", f"{S3}/sft/claude_decomp.jsonl",
                         "TRAIN component — claude_decomp",
                         "Task-decomposition mined from claude-code logs (⚠ 16.2% scaffold artifacts — filter on assembly).", per=3))
    # TEST
    parts.append(sec_generic(f"{D}/data_pool_v2/gold_routing_eval.jsonl", f"{S3} (docs)",
                             "TEST — gold_routing_eval (CLEAN, trustworthy)",
                             "Curated routing accept-set. Grader = accept-set membership. This is the eval that "
                             "gives the trustworthy 0.849. schema has candidates + accept.",
                             ["query", "candidates", "accept", "gold"], per=4))
    parts.append(sec_generic(f"{D}/routing_data_v1/realbio_routing_eval.jsonl", f"{S3} (docs)",
                             "TEST — realbio_routing_eval", "RealBio routing eval.",
                             ["query", "candidates", "accept", "gold"], per=3))
    parts.append(sec_generic(f"{D}/routing_data_v1/dbtest_routing_eval.jsonl", f"{S3} (docs)",
                             "TEST — dbtest_routing_eval", "dbtest routing eval.",
                             ["query", "candidates", "accept", "gold"], per=3))
    parts.append(sec_generic(f"{D}/routing_data_v1/removal_eval.jsonl", f"{S3} (docs)",
                             "TEST — removal_eval (out-of-catalog composition)",
                             "No single workflow fits → decompose. Grader = step overlap + abstention.",
                             ["query", "candidates", "ground_truth_steps"], per=3))
    parts.append(sec_sft("ceb", f"{D}/data_pool_v2/corpus_eval_big.jsonl", f"{S3} (docs)",
                         "TEST — corpus_eval_big (⚠ generator-made, ~38% routing gold hallucinated)",
                         "Broad multi-task eval built by the same ungrounded generator; use content-overlap "
                         "grader only, NOT as ground truth for routing. Kept for coverage/context.", per=2))
    doc = "\n".join(parts)
    open(a.out, "w").write(doc)
    print(f"DATA CATALOG -> {a.out} ({len(doc):,} chars)")


if __name__ == "__main__":
    raise SystemExit(main())
