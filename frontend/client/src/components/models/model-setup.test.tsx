import { afterEach, expect, it, vi } from 'vitest';
import { cleanup, fireEvent, render, screen, waitFor } from '@testing-library/react';
import { ModelSetup, modelSetupUrl } from './model-setup';
const setProject = vi.fn();
vi.mock('@/contexts/active-project-context', () => ({ useActiveProjectSafe: () => ({ activeProjectId: 'project-1', projects: [{ id: 'project-1', name: 'Research' }], setActiveProjectId: setProject }) }));
afterEach(() => { cleanup(); vi.unstubAllGlobals(); });
it('prepares a project-preserving training draft with exact file identity and no execution request', async () => {
 const fetcher = vi.fn().mockResolvedValue({ ok: true, json: async () => ({ files: [{ id: 'f1', name: 'features.csv' }] }) }); vi.stubGlobal('fetch', fetcher);
 const next = vi.fn(); render(<ModelSetup onContinue={next} />);
 await waitFor(() => expect(screen.getByText('features.csv')).toBeInTheDocument());
 fireEvent.change(screen.getByLabelText('Dataset'), { target: { value: 'f1' } });
 fireEvent.change(screen.getByLabelText('Target / label column'), { target: { value: 'subtype' } });
 fireEvent.click(screen.getByText('Review in chat'));
 expect(next).toHaveBeenCalledOnce();
 const query = new URL(next.mock.calls[0][0], 'https://example.test').searchParams;
 expect(query.get('project')).toBe('project-1'); expect(query.get('attachFile')).toBe('f1');
 expect(query.get('draft')).toContain('Target/label column: subtype');
 expect(query.get('draft')).toContain('model_type=sklearn_tabular');
 expect(query.get('draft')).toContain('before execution');
 expect(fetcher).toHaveBeenCalledTimes(1);
});
it('preserves both assay and candidate attachments in a rounds request', () => {
 const query = new URL(modelSetupUrl('p', 'assay', 'review only', 'candidates'), 'https://example.test').searchParams;
 expect(query.getAll('attachFile')).toEqual(['assay', 'candidates']);
 expect(query.get('draft')).toBe('review only');
});
it('uses supported task-specific metrics and sends the exact registration gate parameters', async () => {
 vi.stubGlobal('fetch', vi.fn().mockResolvedValue({ ok: true, json: async () => ({ files: [{ id: 'f1', name: 'features.csv' }] }) }));
 const next = vi.fn(); render(<ModelSetup onContinue={next} />);
 await screen.findByText('features.csv');
 fireEvent.change(screen.getByLabelText('Dataset'), { target: { value: 'f1' } });
 fireEvent.change(screen.getByLabelText('Target / label column'), { target: { value: 'response' } });
 fireEvent.change(screen.getByLabelText('Model name'), { target: { value: 'response-predictor' } });
 fireEvent.change(screen.getByLabelText('Task type'), { target: { value: 'regression' } });
 expect(screen.getByLabelText('Validation metric')).toHaveValue('r2');
 expect(screen.queryByRole('option', { name: 'Spearman correlation' })).toBeNull();
 expect(screen.queryByRole('option', { name: 'Accuracy' })).toBeNull();
 fireEvent.change(screen.getByLabelText('Minimum acceptable metric'), { target: { value: '0.8' } });
 fireEvent.click(screen.getByText('Review in chat'));
 const draft = new URL(next.mock.calls[0][0], 'https://example.test').searchParams.get('draft');
 expect(draft).toContain('target_col=response'); expect(draft).toContain('task_type=regression'); expect(draft).toContain('model_name=response-predictor'); expect(draft).toContain('metric=r2'); expect(draft).toContain('gate_threshold=0.8');
});
