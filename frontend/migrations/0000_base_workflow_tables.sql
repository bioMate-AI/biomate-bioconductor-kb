-- Fresh installations need these base tables before later ALTER migrations.
-- Existing deployments retain their tables and data. Columns match shared/schema.ts.

CREATE TABLE IF NOT EXISTS "execution_runs" (
	"id" varchar PRIMARY KEY DEFAULT gen_random_uuid() NOT NULL,
	"parent_run_id" varchar,
	"run_sequence" text DEFAULT '1',
	"user_id" text,
	"project_id" text,
	"chat_session_id" text,
	"mode" text DEFAULT 'sandbox',
	"workflow_name" text NOT NULL,
	"workflow_definition" text,
	"data_scope" text,
	"parameters" text,
	"galaxy_invocation_id" text,
	"galaxy_history_id" text,
	"galaxy_workflow_id" text,
	"status" text DEFAULT 'configuring',
	"started_at" timestamp,
	"completed_at" timestamp,
	"paused_at" timestamp,
	"pause_reason" text,
	"error_message" text,
	"total_steps" text DEFAULT '0',
	"completed_steps" text DEFAULT '0',
	"current_step_index" text,
	"current_step_name" text,
	"percent_complete" text DEFAULT '0',
	"steps" text,
	"metrics" text,
	"interactions" text,
	"recommendations" text,
	"comparison" text,
	"execution_json" text,
	"nextflow_run_id" text,
	"nextflow_output_dir" text,
	"created_at" timestamp DEFAULT now(),
	"updated_at" timestamp DEFAULT now()
);

CREATE TABLE IF NOT EXISTS "experiments" (
	"id" varchar PRIMARY KEY DEFAULT gen_random_uuid() NOT NULL,
	"user_id" varchar NOT NULL,
	"hypothesis" text NOT NULL,
	"workflow_id" text NOT NULL,
	"workflow_name" text,
	"control_label" text DEFAULT 'Control',
	"experimental_label" text DEFAULT 'Experimental',
	"control_params" text NOT NULL,
	"experimental_params" text NOT NULL,
	"metrics" text NOT NULL,
	"status" text DEFAULT 'pending' NOT NULL,
	"control_run_id" text,
	"experimental_run_id" text,
	"comparison_result" text,
	"narrative" text,
	"error_message" text,
	"created_at" timestamp DEFAULT now(),
	"updated_at" timestamp DEFAULT now()
);

CREATE TABLE IF NOT EXISTS "workflow_executions" (
	"id" varchar PRIMARY KEY DEFAULT gen_random_uuid() NOT NULL,
	"user_id" text NOT NULL,
	"project_id" text,
	"galaxy_invocation_id" text NOT NULL,
	"galaxy_workflow_id" text,
	"galaxy_history_id" text,
	"workflow_name" text,
	"workflow_definition" text,
	"status" text DEFAULT 'new',
	"started_at" timestamp DEFAULT now(),
	"completed_at" timestamp,
	"error_message" text,
	"total_steps" text,
	"completed_steps" text,
	"created_at" timestamp DEFAULT now(),
	"updated_at" timestamp DEFAULT now()
);
