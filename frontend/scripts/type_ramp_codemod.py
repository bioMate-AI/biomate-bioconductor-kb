#!/usr/bin/env python3
"""Migrate ad-hoc font sizes onto the type-ramp tokens (--fs-*).

Plan JSON (Gemini-authored, see docs/20261110_UI_TYPE_RAMP_GEMINI.md):
  {"tokens": {"--fs-xs": {"size": "11px", "line": "1.2"}, ...},
   "px_map": {"10": "--fs-xs", ...},           # every legacy px value -> token
   "tailwind": {"xs": "--fs-sm", ...}}          # Tailwind named sizes -> token

  python3 scripts/type_ramp_codemod.py plan.json --apply          # rewrite source
  python3 scripts/type_ramp_codemod.py plan.json --preview out.css # CSS that emulates
      the migration on an un-migrated build (for rendering on dev before deploy)

Only CSS font-size declarations, React style objects and Tailwind text-[Npx]
classes are touched. Chart props (Recharts tick=/label=, SVG fontSize=) are
skipped: presentation attributes do not resolve var().
"""
import json, re, sys, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent / "client" / "src"
# ind-report.css is excluded: it styles the printed IND document, not the app UI.
CSS_FILES = ["styles/reference-design.css", "styles/workflow-panel.css", "index.css"]
TOKEN_START, TOKEN_END = "/* type-ramp:start", "/* type-ramp:end */"
CHART_LINE = re.compile(r"tick=|label=\{\{|tickLine|fontSize=|<text\b")
INLINE = re.compile(r"""fontSize:(\s*)(['"]?)(\d+(?:\.\d+)?)(px)?\2""")
ARBITRARY = re.compile(r"text-\[(\d+(?:\.\d+)?)px\]")
CSS_DECL = re.compile(r"font-size:(\s*)(\d+(?:\.\d+)?)px")


def num(s):
    return str(float(s)).rstrip("0").rstrip(".")


def load(path):
    plan = json.load(open(path))
    plan["px_map"] = {num(k): v for k, v in plan["px_map"].items()}
    return plan


def step(plan, px):
    tok = plan["px_map"].get(num(px))
    if not tok:
        raise SystemExit(f"plan has no mapping for {px}px")
    return tok


def token_block(plan):
    lines = [f"{TOKEN_START} — generated by scripts/type_ramp_codemod.py; edit the plan, not here */"]
    for name, t in plan["tokens"].items():
        lines.append(f"  {name}: {t['size']};")
        lines.append(f"  {name.replace('--fs-', '--lh-')}: {t['line']};")
    lines.append(f"  {TOKEN_END}")
    return "\n  ".join(lines)


def tsx_files():
    return [p for p in ROOT.rglob("*.tsx") if ".test." not in p.name]


def rewrite_tsx(plan, src):
    out = []
    for line in src.split("\n"):
        if not CHART_LINE.search(line):
            line = INLINE.sub(lambda m: f"fontSize:{m.group(1)}'var({step(plan, m.group(3))})'", line)
        line = ARBITRARY.sub(lambda m: "text-" + step(plan, m.group(1))[2:], line)  # text-fs-xs
        out.append(line)
    return "\n".join(out)


def rewrite_css(plan, src):
    return CSS_DECL.sub(lambda m: f"font-size:{m.group(1)}var({step(plan, m.group(2))})", src)


def tailwind_font_sizes(plan):
    entries = {}
    for name in plan["tokens"]:
        key = name[2:]  # fs-xs
        entries[key] = [f"var({name})", {"lineHeight": f"var({name.replace('--fs-', '--lh-')})"}]
    for tw, name in plan["tailwind"].items():
        entries[tw] = [f"var({name})", {"lineHeight": f"var({name.replace('--fs-', '--lh-')})"}]
    return entries


def apply(plan):
    changed = 0
    for p in tsx_files():
        s = p.read_text()
        n = rewrite_tsx(plan, s)
        if n != s:
            p.write_text(n); changed += 1
    for rel in CSS_FILES:
        p = ROOT / rel
        s = p.read_text()
        n = rewrite_css(plan, s)
        if rel == "styles/reference-design.css":
            block = token_block(plan)
            if TOKEN_START in n:
                a = n.index(TOKEN_START); b = n.index(TOKEN_END, a) + len(TOKEN_END)
                n = n[:a] + block.strip() + n[b:]
            else:
                n = n.replace(":root {", ":root {\n  " + block, 1)
        if n != s:
            p.write_text(n); changed += 1
    cfg = ROOT.parent.parent / "tailwind.config.js"
    s = cfg.read_text()
    rows = [f'        "{k}": ["{v[0]}", {{ lineHeight: "{v[1]["lineHeight"]}" }}],'
            for k, v in tailwind_font_sizes(plan).items()]
    body = "{\n        // type ramp — generated by scripts/type_ramp_codemod.py\n" + "\n".join(rows) + "\n      }"
    if "fontSize: {" in s:
        s = re.sub(r"fontSize: \{.*?\n      \},", "fontSize: " + body + ",", s, count=1, flags=re.S)
    else:
        s = s.replace("      fontFamily: {", "      fontSize: " + body + ",\n      fontFamily: {", 1)
    cfg.write_text(s)
    print(f"rewrote {changed} files + tailwind.config.js")


def preview(plan, out):
    """CSS that makes an un-migrated build render as if migrated."""
    css = [":root {\n  " + token_block(plan) + "\n}"]
    for tw, name in plan["tailwind"].items():
        css.append(f".text-{tw.replace('.', chr(92) + '.')} {{ font-size: var({name}) !important; line-height: var({name.replace('--fs-', '--lh-')}) !important; }}")
    for px, name in plan["px_map"].items():
        esc = px.replace(".", "\\.")
        css.append(f".text-\\[{esc}px\\] {{ font-size: var({name}) !important; }}")
        css.append(f'[style*="font-size: {px}px"] {{ font-size: var({name}) !important; }}')
    for rel in ["styles/reference-design.css", "styles/workflow-panel.css"]:
        css.append(rewrite_css(plan, (ROOT / rel).read_text()))
    pathlib.Path(out).write_text("\n".join(css))
    print("preview css ->", out)


if __name__ == "__main__":
    plan = load(sys.argv[1])
    if sys.argv[2] == "--apply":
        apply(plan)
    elif sys.argv[2] == "--preview":
        preview(plan, sys.argv[3])
