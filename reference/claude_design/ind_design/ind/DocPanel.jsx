// Right-panel document viewer + inline feedback surfaces (B2-B5)

const IndDocPanel = ({ doc, audit, region, onRegionChange, onSign, onAudit, onVersionsClick,
  showVersions, onVersionsClose, onDownload, onChatHandoff }) => {
  const [editedParas, setEditedParas] = React.useState({});  // {pid: true}
  const [showCitePop, setShowCitePop] = React.useState(null); // pid where popover shows
  const [regenSection, setRegenSection] = React.useState(null);
  const [regenInstr, setRegenInstr] = React.useState('');
  const SECTION_ORDER = ['2.6.1', '2.6.2', '2.6.3', '2.6.4', '2.6.5', '2.6.6'];

  const markEdited = (pid) => setEditedParas(prev => ({ ...prev, [pid]: true }));

  return (
    <aside className="ind-doc-panel" data-tour="ind-doc-panel">
      <header className="ind-doc-head">
        <div className="ind-doc-title">
          CTD Module 2.6 — Nonclinical Written Summaries
          <span className="ver-chip" onClick={onVersionsClick} data-tour="ind-version-chip">v{doc.version}</span>
        </div>
        <div className="ind-doc-sub">BM-0042 · Acme Therapeutics · NSCLC</div>
        <div className="ind-doc-meta">
          {doc.signed ? (
            <span className="adapter-badge" title="This document is signed and frozen">
              Signed · v{doc.version}
            </span>
          ) : (
            <span style={{color: 'var(--ind-warn)', fontWeight: 600}}>Not yet signed</span>
          )}
          <span>·</span>
          <span>FDA · EMA · NMPA · PMDA</span>
          <span>·</span>
          <span>{doc.generatedAt}</span>
        </div>
        <div className="ind-doc-region" data-tour="ind-doc-region">
          <span>Region:</span>
          <select value={region} onChange={(e) => onRegionChange(e.target.value)}>
            <option value="FDA">FDA</option>
            <option value="EMA">EMA</option>
            <option value="NMPA">NMPA</option>
            <option value="PMDA">PMDA</option>
            <option value="ALL">All regions (combined)</option>
          </select>
          <span style={{color:'var(--ind-text-dim)', marginLeft: 8}}>
            {region === 'NMPA' ? 'incl. GLP declaration' : region === 'PMDA' ? 'incl. ethnic bridging' : ''}
          </span>
        </div>
      </header>

      <nav className="ind-doc-tabs" data-tour="ind-doc-tabs">
        {SECTION_ORDER.map(id => {
          const sec = doc.sections.find(s => s.id === id);
          return (
            <button
              key={id}
              className="ind-doc-tab"
              onClick={() => {
                const el = document.querySelector(`[data-section="${id}"]`);
                if (el) el.scrollIntoView({ block: 'start' });
              }}
            >
              §{id}
              <span className={`marker ${sec?.coverage || 'none'}`}/>
            </button>
          );
        })}
      </nav>

      {showVersions && <VersionHistory doc={doc} onClose={onVersionsClose}/>}

      <div className="ind-doc-body">
        {doc.sections.map(section => (
          <DocSection key={section.id}
            section={section}
            audit={audit}
            onEdit={markEdited}
            onCiteAdd={(pid) => setShowCitePop(pid)}
            onRegenerate={(secId) => setRegenSection(secId)}
            editedParas={editedParas}
          />
        ))}

        {doc.sections.length > 0 && (
          <div style={{marginTop: 24, padding: 12, background: 'var(--ind-bg-sub)', borderRadius: 8, fontSize: 12.5}}>
            <b>💬 Discuss in chat →</b> Have a question about a specific result?{' '}
            <button className="ind-link" onClick={onChatHandoff}>Open the campaign in BioMate chat</button>
            {' '}— campaign context is pre-loaded so you can ask things like
            "Why is BM-0042 flagged for DILI?"
          </div>
        )}
      </div>

      <footer className="ind-doc-foot" data-tour="ind-doc-foot">
        <div className="row">
          <span>SHA-256: {doc.shaPrefix}…</span>
          <span>·</span>
          <span>Generated by BioMate v1.0 · {doc.generatedAt}</span>
        </div>
        <div className="row">
          <span>Model: Gemini 3 Flash (T=0.3) · ADMET-AI v2.0</span>
          <span>·</span>
          <span>Requires human review</span>
        </div>
        <div className="row actions">
          {!doc.signed
            ? <span className="mark-unsigned">[Not yet signed]</span>
            : <span className="mark-signed">Signed by: {doc.signedBy} · Sig {doc.shaPrefix}…</span>}
          <span style={{flex: 1}}/>
          <button className="ind-btn sm" onClick={onAudit}>
            <CroIcon name="shield" size={12}/> View audit
          </button>
          <button className="ind-btn sm" onClick={() => onDownload('md')}>
            <CroIcon name="download" size={12}/> .md
          </button>
          <button className="ind-btn sm" onClick={() => onDownload('docx')}>
            <CroIcon name="download" size={12}/> .docx
          </button>
          {!doc.signed && (
            <button className="ind-btn sm primary" onClick={onSign}>
              <CroIcon name="signature" size={12}/> Sign
            </button>
          )}
        </div>
      </footer>

      {showCitePop && (
        <CitePopover pid={showCitePop} onClose={() => setShowCitePop(null)}/>
      )}

      {regenSection && (
        <RegenerateModal
          section={regenSection}
          onClose={() => { setRegenSection(null); setRegenInstr(''); }}
          instruction={regenInstr}
          setInstruction={setRegenInstr}
        />
      )}
    </aside>
  );
};

// Individual section in the doc viewer
const DocSection = ({ section, audit, onEdit, onCiteAdd, onRegenerate, editedParas }) => {
  const findingsForSection = audit.findings.filter(f =>
    f.section === `§${section.id}` ||
    f.section.startsWith(`§${section.id}.`)
  );
  const hasMinor = findingsForSection.some(f => f.severity === 'MINOR' && !f.addressed);

  const subs = section.subs || [{ id: section.id, title: section.title, body: window.IND_SECTION_BODY[section.id] }];

  return (
    <article
      className={`ind-doc-section ${hasMinor ? 'has-finding' : ''}`}
      data-section={section.id}
    >
      <h3>{section.title}</h3>
      {section.subs ? section.subs.map(sub => {
        const body = window.IND_SECTION_BODY[sub.id] || '';
        const pid = `p-${sub.id}`;
        const subFinding = findingsForSection.find(f => f.section === `§${sub.id}`);
        return (
          <div key={sub.id}>
            <h4>§{sub.id}  {sub.title}</h4>
            {body
              ? <p
                  data-pid={pid}
                  data-edited={editedParas[pid] || undefined}
                  contentEditable
                  suppressContentEditableWarning
                  onBlur={(e) => {
                    if (e.target.innerText.trim() !== body.trim()) onEdit(pid);
                  }}
                >
                  {body}
                  {subFinding && (
                    <span
                      className="finding-chip"
                      title={subFinding.desc}
                      onClick={(e) => { e.stopPropagation(); window.dispatchEvent(new CustomEvent('ind-open-audit')); }}
                    >
                      ⚠ {subFinding.severity}
                    </span>
                  )}
                  {' '}
                  <span className="cite-add" title="Suggest a citation" onClick={() => onCiteAdd(pid)}>+</span>
                </p>
              : <div className="skel">┄ ┄ ┄ §{sub.id} {sub.wait || '— ready'} ┄ ┄ ┄</div>}
            <button className="regen-btn" onClick={() => onRegenerate(sub.id)}>
              ↻ Regenerate ▾
            </button>
          </div>
        );
      }) : (
        <p
          data-pid={`p-${section.id}`}
          data-edited={editedParas[`p-${section.id}`] || undefined}
          contentEditable
          suppressContentEditableWarning
          onBlur={(e) => {
            const body = window.IND_SECTION_BODY[section.id] || '';
            if (e.target.innerText.trim() !== body.trim()) onEdit(`p-${section.id}`);
          }}
        >
          {window.IND_SECTION_BODY[section.id]}
          {' '}
          <span className="cite-add" title="Suggest a citation" onClick={() => onCiteAdd(`p-${section.id}`)}>+</span>
          {section.note && (
            <span className="finding-chip" style={{background: 'var(--ind-warn-soft)', color: 'var(--ind-warn)'}}>
              ⚠ partial
            </span>
          )}
        </p>
      )}
      {section.note && (
        <div style={{fontSize: 11.5, color: 'var(--ind-warn)', fontStyle: 'italic', marginTop: 4}}>
          ⚠ {section.note}
        </div>
      )}
    </article>
  );
};

// ── Citation suggest popover (B4) ─────────────────────────────
const CitePopover = ({ pid, onClose }) => {
  const [gid, setGid] = React.useState('');
  const [why, setWhy] = React.useState('');
  const ref = React.useRef(null);
  React.useEffect(() => {
    // Position next to the cite-add icon if findable
    const anchor = document.querySelector(`[data-pid="${pid}"] .cite-add`);
    if (anchor && ref.current) {
      const r = anchor.getBoundingClientRect();
      const panel = anchor.closest('.ind-doc-panel');
      const panelRect = panel.getBoundingClientRect();
      ref.current.style.left = `${r.left - panelRect.left + 20}px`;
      ref.current.style.top  = `${r.top  - panelRect.top  + 20}px`;
    }
  }, [pid]);
  return (
    <>
      <div style={{position: 'absolute', inset: 0, zIndex: 25}} onClick={onClose}/>
      <div className="cite-popover" ref={ref} onClick={(e) => e.stopPropagation()} data-tour="ind-cite-popover">
        <h4>Suggest a citation</h4>
        <div className="ind-field">
          <label>Guideline ID</label>
          <input value={gid} onChange={(e) => setGid(e.target.value)}
            placeholder="e.g. CDE 化学药物非临床研究技术指导原则"/>
        </div>
        <div className="ind-field">
          <label>Why it applies</label>
          <textarea value={why} onChange={(e) => setWhy(e.target.value)}
            rows={2} style={{fontFamily: 'inherit'}}/>
        </div>
        <div style={{display: 'flex', gap: 8, marginTop: 4}}>
          <button className="ind-btn sm" onClick={onClose}>Add to document only</button>
          <button className="ind-btn sm primary" onClick={onClose}>Also suggest for BioMate</button>
        </div>
      </div>
    </>
  );
};

// ── Regenerate-with-instruction modal (B5) ────────────────────
const RegenerateModal = ({ section, onClose, instruction, setInstruction }) => {
  return (
    <div className="modal-backdrop" onClick={onClose} style={{zIndex: 50}}>
      <div className="modal" onClick={(e) => e.stopPropagation()}
        style={{background: 'white', borderRadius: 10, padding: 18, maxWidth: 440, width: '90%'}}
        data-tour="ind-regenerate-modal">
        <h3 style={{fontSize: 14, fontWeight: 700, marginBottom: 10}}>
          Regenerate §{section}
        </h3>
        <div style={{display: 'flex', flexDirection: 'column', gap: 8}}>
          <label style={{display: 'flex', gap: 8, alignItems: 'center', fontSize: 13}}>
            <input type="radio" name="regen" defaultChecked={!instruction}/>
            Regenerate as is
          </label>
          <label style={{display: 'flex', gap: 8, alignItems: 'flex-start', fontSize: 13}}>
            <input type="radio" name="regen" defaultChecked={!!instruction}/>
            <span style={{flex: 1}}>
              Regenerate with instruction:
              <textarea
                value={instruction}
                onChange={(e) => setInstruction(e.target.value)}
                placeholder="e.g. Use more conservative language about the Ames equivocal finding"
                rows={3}
                style={{
                  width: '100%', marginTop: 4, padding: 8,
                  border: '1px solid var(--ind-border-strong)', borderRadius: 6,
                  fontFamily: 'inherit', fontSize: 12.5,
                }}
              />
            </span>
          </label>
        </div>
        <div style={{display: 'flex', gap: 8, justifyContent: 'flex-end', marginTop: 14}}>
          <button className="ind-btn" onClick={onClose}>Cancel</button>
          <button className="ind-btn primary" onClick={onClose}>↻ Regenerate</button>
        </div>
      </div>
    </div>
  );
};

