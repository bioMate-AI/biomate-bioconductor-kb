# ── Package.json fix ──────────────────────────────────────────────────────────

def _fix_pkg():
    pkg = os.path.join(NODE_TOOL, "package.json")
    with open(pkg) as f:
        data = json.load(f)
    data.pop("type", None)
    with open(pkg, "w") as f:
        json.dump(data, f)


# ── Node recorder script ──────────────────────────────────────────────────────

def write_recorder(key, cfg, timings, html_url):
    tour_label = cfg["tour_label"]
    lead_in_ms = cfg["lead_in_ms"]
    trail_ms   = cfg["trail_ms"]

    steps_json  = json.dumps([t["hold_ms"] for t in timings["steps"]])
    total_ms    = timings["total_ms"] + lead_in_ms + trail_ms

    frames_dir  = f"/tmp/biomate_{key}_frames"
    script_path = f"/tmp/biomate_{key}_record.js"

    # Build tour-start block and screencast-start position.
    # CRITICAL: We start CDP screencast AFTER the tour callout is visible
    # so the picker dialog never appears in any captured frame.
    if tour_label:
        # Research Agent UI: click .tut-btn → picker opens → click item → wait for
        # picker to close and .tour-callout to appear → THEN start screencast.
        tour_setup_js = f"""
  // ── Set up tour (before screencast starts) ──
  const tutBtn = await page.$('.tut-btn');
  if (!tutBtn) {{ console.error('Tutorial button not found'); process.exit(1); }}
  await tutBtn.click();
  await new Promise(r => setTimeout(r, 600));

  // Find and click the matching picker item
  const items = await page.$$('.tour-picker-item');
  let found = false;
  for (const item of items) {{
    const label = await page.evaluate(el => el.querySelector('.tour-picker-item-label')?.textContent || '', item);
    if (label.includes({json.dumps(tour_label[:30])})) {{
      await item.click();
      found = true;
      break;
    }}
  }}
  if (!found) {{ console.error('Picker item not found: {tour_label[:30]}'); process.exit(1); }}

  // Wait for picker to dismiss and tour callout (step 0) to render
  await page.waitForSelector('.tour-callout', {{ timeout: 5000 }});
  await page.waitForFunction(
    () => !document.querySelector('.tour-picker-backdrop'),
    {{ timeout: 3000 }}
  );
  console.log('Tour step 0 visible — starting screencast');
"""
    else:
        # IND Report: .tut-btn starts tour directly (no picker)
        tour_setup_js = f"""
  // ── Set up tour (before screencast starts) ──
  const tutBtn = await page.$('.tut-btn');
  if (!tutBtn) {{ console.error('Tutorial button not found'); process.exit(1); }}
  await tutBtn.click();

  // Wait for tour callout to render
  await page.waitForSelector('.tour-callout', {{ timeout: 5000 }});
  console.log('Tour step 0 visible — starting screencast');
"""

    script = f"""
const puppeteer = require('/tmp/biomate_video_tool/node_modules/puppeteer-core');
const fs = require('fs');
const path = require('path');

const CHROME  = {json.dumps(CHROME)};
const HTML    = {json.dumps(html_url)};
const FRAMES  = {json.dumps(frames_dir)};
const STEPS   = {steps_json};    // hold_ms per step
const LEAD    = {lead_in_ms};
const TRAIL   = {trail_ms};

(async () => {{
  fs.mkdirSync(FRAMES, {{ recursive: true }});

  const browser = await puppeteer.launch({{
    executablePath: CHROME,
    headless: 'new',
    timeout: 90000,
    args: [
      '--no-sandbox', '--disable-setuid-sandbox',
      '--window-size=1920,1080',
      '--force-device-scale-factor=1',
      '--disable-dev-shm-usage',
      '--disable-background-timer-throttling',
      '--disable-renderer-backgrounding',
      '--disable-backgrounding-occluded-windows',
      '--user-data-dir=/tmp/biomate_chrome_profile_{key}',
    ],
    defaultViewport: {{ width: 1920, height: 1080 }},
  }});

  const page = await browser.newPage();
  await page.goto(HTML, {{ waitUntil: 'load', timeout: 30000 }});
  await new Promise(r => setTimeout(r, 7000));   // wait for Babel transpile + React init (JSX loads async; bioc HTML has extra scripts)

  // Disable all autoAdvance timers so WE control step timing
  await page.evaluate(() => {{
    if (window.DEMO_TOURS) {{
      Object.values(window.DEMO_TOURS).forEach(t => {{
        if (t.steps) t.steps.forEach(s => {{ delete s.autoAdvance; }});
      }});
    }}
  }});

  // Keep compositor generating frames at ~30fps by animating an invisible element.
  // Without this, static pages between ArrowRight presses deliver <1 fps from CDP.
  await page.evaluate(() => {{
    const ticker = document.createElement('div');
    ticker.style.cssText = 'position:fixed;width:1px;height:1px;opacity:0.001;pointer-events:none;z-index:-1;top:0;left:0';
    document.body.appendChild(ticker);
    let v = 0;
    const tick = () => {{ ticker.style.transform = `translateX(${{(v++%2)*0.01}}px)`; requestAnimationFrame(tick); }};
    requestAnimationFrame(tick);
  }});

  // Hide dev UI chrome (tweaks panel, etc.) if present
  await page.evaluate(() => {{
    ['#ui', '#hint', '#prog', '.tweaks-panel', '#tweaks'].forEach(sel => {{
      const el = document.querySelector(sel);
      if (el) el.style.display = 'none';
    }});
  }});

{tour_setup_js}

  // ── Start CDP screencast AFTER tour is active (no picker in frames) ──
  // Stream frames directly to disk to avoid OOM on long videos.
  // everyNthFrame:1 = every frame ≈ 30fps; higher quality than :2 for tutorial vids.
  const client = await page.createCDPSession();
  let frameIdx = 0;
  const tsStream = fs.createWriteStream(path.join(FRAMES, 'timestamps.ndjson'));

  client.on('Page.screencastFrame', async (e) => {{
    try {{
      const p = path.join(FRAMES, `frame_${{String(frameIdx).padStart(5,'0')}}.png`);
      fs.writeFileSync(p, Buffer.from(e.data, 'base64'));
      tsStream.write(JSON.stringify(e.metadata.timestamp) + '\\n');
      frameIdx++;
      await client.send('Page.screencastFrameAck', {{ sessionId: e.sessionId }});
    }} catch (err) {{
      // Ignore ack errors after browser closes
    }}
  }});

  await client.send('Page.startScreencast', {{
    format: 'png', maxWidth: 1920, maxHeight: 1080, everyNthFrame: 1,
  }});

  console.log(`Screencast started — ${{STEPS.length}} steps, lead=${{LEAD}}ms`);

  // Press ArrowLeft once immediately to ensure we're on step 0 (guards against any
  // auto-advance that fired before the screencast started; no-op if already at step 0).
  await page.keyboard.press('ArrowLeft');
  await new Promise(r => setTimeout(r, 200));

  // Lead-in: first step renders/animates in
  await new Promise(r => setTimeout(r, LEAD));

  // Step through: hold for each step's duration, then ArrowRight
  for (let i = 0; i < STEPS.length; i++) {{
    await new Promise(r => setTimeout(r, STEPS[i]));
    await page.keyboard.press('ArrowRight');
    await new Promise(r => setTimeout(r, 80));   // settle for transition animation
    if (i < STEPS.length - 1) {{
      console.log(`  Step ${{i+1}}/${{STEPS.length}} advanced`);
    }}
  }}

  // Trail: last step stays visible
  await new Promise(r => setTimeout(r, TRAIL));

  await client.send('Page.stopScreencast');
  tsStream.end();
  await browser.close();

  // Read timestamps from ndjson
  const tsLines = fs.readFileSync(path.join(FRAMES, 'timestamps.ndjson'), 'utf8')
    .trim().split('\\n').filter(Boolean).map(Number);

  console.log(`Captured ${{frameIdx}} frames`);
  if (frameIdx === 0) {{ console.error('No frames!'); process.exit(1); }}

  fs.writeFileSync(path.join(FRAMES, 'timestamps.json'), JSON.stringify(tsLines));
  const dur = tsLines[tsLines.length-1] - tsLines[0];
  console.log(`Duration: ${{dur.toFixed(2)}}s, FPS avg: ${{(frameIdx/dur).toFixed(1)}}`);
}})().catch(e => {{ console.error(e); process.exit(1); }});
"""
    with open(script_path, "w") as f:
        f.write(script)
    return frames_dir, script_path


# ── Video assembly ────────────────────────────────────────────────────────────

def build_video(key, cfg, timings, frames_dir):
    ts_path = os.path.join(frames_dir, "timestamps.json")
    with open(ts_path) as f:
        timestamps = json.load(f)

    n  = len(timestamps)
    t0 = timestamps[0]
    total_s = timestamps[-1] - t0

    target_s = (timings["total_ms"] + cfg["lead_in_ms"] + cfg["trail_ms"]) / 1000

    # Build ffmpeg concat file with per-frame duration
    concat_path = f"/tmp/biomate_{key}_concat.txt"
    with open(concat_path, "w") as f:
        for i in range(n):
            img = os.path.join(frames_dir, f"frame_{str(i).zfill(5)}.png")
            dur = (timestamps[i+1] - timestamps[i]) if i < n-1 else 1.0/30
            f.write(f"file '{img}'\nduration {dur:.6f}\n")
        f.write(f"file '{os.path.join(frames_dir, f'frame_{str(n-1).zfill(5)}.png')}'\n")

    extend_s = max(0, target_s - total_s)
    print(f"  Frames: {n}, captured={total_s:.1f}s, target={target_s:.1f}s, extend={extend_s:.1f}s")

    stitched = f"/tmp/biomate_{key}_stitched.mp4"
    r = subprocess.run([
        "ffmpeg", "-y", "-f", "concat", "-safe", "0", "-i", concat_path,
        "-vf", "scale=1920:1080:flags=lanczos,format=yuv420p",
        "-c:v", "h264_videotoolbox", "-b:v", "18M",
        "-t", f"{total_s:.3f}", stitched,
    ], capture_output=True)
    if r.returncode != 0:
        print(r.stderr.decode()[-2000:]); raise RuntimeError("stitch failed")

    raw_video = f"/tmp/biomate_{key}_raw.mp4"
    if extend_s > 0.1:
        r2 = subprocess.run([
            "ffmpeg", "-y", "-i", stitched,
            "-vf", f"tpad=stop_mode=clone:stop_duration={extend_s:.3f}",
            "-c:v", "h264_videotoolbox", "-b:v", "18M",
            "-pix_fmt", "yuv420p", raw_video,
        ], capture_output=True)
        if r2.returncode != 0:
            print(r2.stderr.decode()[-2000:]); raise RuntimeError("extend failed")
    else:
        shutil.copy(stitched, raw_video)
    return raw_video


def merge_audio(key, raw_video, audio):
    output = os.path.join(BASE, f"{key}_tutorial.mp4")
    subprocess.run([
        "ffmpeg", "-y",
        "-i", raw_video, "-i", audio,
        "-c:v", "copy", "-c:a", "aac", "-b:a", "192k",
        "-shortest", output,
    ], check=True, capture_output=True)
    size_mb = os.path.getsize(output) / (1024 * 1024)
    print(f"  → {output}  ({size_mb:.1f} MB)")
    return output


# ── Per-tutorial runner ───────────────────────────────────────────────────────

def record_tutorial(key, cfg, no_audio=False):
    clips_dir  = os.path.join(CLIPS, key)
    timings_fp = os.path.join(clips_dir, "timings.json")
    audio      = os.path.join(clips_dir, "combined.mp3")

    if not os.path.exists(timings_fp):
        print(f"  ERROR: {timings_fp} not found. Run generate_vo.py first.")
        return
    if not no_audio and not os.path.exists(audio):
        print(f"  ERROR: {audio} not found. Run generate_vo.py first (or use --no-audio).")
        return

    with open(timings_fp) as f:
        timings = json.load(f)

    frames_dir = f"/tmp/biomate_{key}_frames"
    if os.path.exists(frames_dir):
        shutil.rmtree(frames_dir)
    os.makedirs(frames_dir)

    label = cfg["url_path"].split("/")[0]
    print(f"\n── {label} › {key} ──")
    print(f"   {len(timings['steps'])} steps, {timings['total_ms']/1000:.1f}s total")

    _fix_pkg()

    # Start local HTTP server so JSX files load correctly
    port, server = start_http_server(BASE)
    html_url = f"http://127.0.0.1:{port}/{cfg['url_path']}"
    print(f"  HTTP server on port {port}: {html_url}")

    try:
        print("  Writing recorder…")
        frames_dir, script_path = write_recorder(key, cfg, timings, html_url)

        print("  Recording via CDP screencast…")
        env = os.environ.copy()
        env["NODE_OPTIONS"] = "--max-old-space-size=4096"
        subprocess.run(["node", script_path], check=True, env=env)
    finally:
        server.shutdown()

    print("  Building video…")
    raw = build_video(key, cfg, timings, frames_dir)

    if no_audio:
        # Copy raw video to output without merging audio (silent)
        output = os.path.join(BASE, f"{key}_tutorial_silent.mp4")
        shutil.copy(raw, output)
        size_mb = os.path.getsize(output) / (1024 * 1024)
        print(f"  → {output}  ({size_mb:.1f} MB)  [silent — no audio merged]")
    else:
        print("  Merging audio…")
        merge_audio(key, raw, audio)


# ── Main ──────────────────────────────────────────────────────────────────────

def main():
    only = None
    no_audio = "--no-audio" in sys.argv
    if "--only" in sys.argv:
        idx = sys.argv.index("--only")
        only = sys.argv[idx + 1] if idx + 1 < len(sys.argv) else None

    keys = [only] if only else list(TUTORIALS.keys())

    for key in keys:
        if key not in TUTORIALS:
            print(f"Unknown: {key}. Options: {list(TUTORIALS.keys())}")
            sys.exit(1)
        record_tutorial(key, TUTORIALS[key], no_audio=no_audio)

    print("\nAll tutorials done!")

if __name__ == "__main__":
    main()
