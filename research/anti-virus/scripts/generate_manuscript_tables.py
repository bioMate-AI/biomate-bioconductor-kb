#!/usr/bin/env python3
"""Export manuscript Table 1 artifacts from archived run data (no fabricated rows)."""
from __future__ import annotations

import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
PLAN_A_TSV = (
    ROOT
    / "research"
    / "anti-virus"
    / "runs"
    / "plan_a_epitope_a44876b7_s3_mirror"
    / "predictions"
    / "PLAN_A_SMOKE_GP.tsv"
)
INHIBITOR_RUN = ROOT / "research" / "anti-virus" / "runs" / "andv_nf_pipeline_20260513T032000Z"
INHIBITOR_DOCK = INHIBITOR_RUN / "04_docking_vina" / "docking_autodock_vina_results.json"
OUT = ROOT / "research" / "anti-virus" / "runs" / "manuscript_figures_v1" / "tables"

# Peptide windows cited in MANUSCRIPT_PLAN_A_VACCINE_v1_0.md Results (both alleles each).
PLAN_A_EXEMPLAR_SEQUENCES = ("GVCYTLTL", "WYLVVLGV", "TSMAQKSF")

DOCKING_LABEL_SHORT = {
    "CC(=O)Oc1ccccc1C(=O)O": "Aspirin",
    "Oc1ccccc1": "Phenol",
    "CC(=O)Nc1ccc(O)cc1": "Paracetamol",
}


def md_table(headers: list[str], rows: list[list[str]]) -> str:
    lines = [
        "| " + " | ".join(headers) + " |",
        "| " + " | ".join("---" for _ in headers) + " |",
    ]
    for row in rows:
        lines.append("| " + " | ".join(row) + " |")
    return "\n".join(lines)


def export_plan_a_table1() -> tuple[Path, int]:
    if not PLAN_A_TSV.is_file():
        raise SystemExit(f"Missing TSV: {PLAN_A_TSV}")
    rows_by_key: dict[tuple[str, str], dict[str, str]] = {}
    with PLAN_A_TSV.open(newline="", encoding="utf-8") as f:
        for row in csv.DictReader(f, delimiter="\t"):
            seq = row.get("sequence", "").strip()
            allele = row.get("allele", "").strip()
            if seq in PLAN_A_EXEMPLAR_SEQUENCES:
                rows_by_key[(seq, allele)] = row
    if len(rows_by_key) != len(PLAN_A_EXEMPLAR_SEQUENCES) * 2:
        raise SystemExit(
            f"Expected {len(PLAN_A_EXEMPLAR_SEQUENCES) * 2} exemplar rows in {PLAN_A_TSV}, got {len(rows_by_key)}"
        )
    table_rows: list[list[str]] = []
    for seq in PLAN_A_EXEMPLAR_SEQUENCES:
        for allele in sorted({k[1] for k in rows_by_key if k[0] == seq}):
            r = rows_by_key[(seq, allele)]
            table_rows.append(
                [
                    seq,
                    allele,
                    f"{float(r['rank']):.4f}",
                    f"{float(r['BA']):.6f}",
                    str(r.get("binder", "")),
                ]
            )
    body = md_table(["Peptide", "Allele", "Rank", "BA", "Binder (MHCnuggets)"], table_rows)
    out = OUT / "PLAN_A_TABLE1.md"
    out.write_text(
        "<!-- Generated by generate_manuscript_tables.py from PLAN_A_SMOKE_GP.tsv — do not edit by hand. -->\n\n"
        f"**Table 1.** Exemplar peptide–allele rows from `{PLAN_A_TSV.relative_to(ROOT)}`.\n\n"
        + body
        + "\n",
        encoding="utf-8",
    )
    return out, len(table_rows)


def export_inhibitor_table1() -> tuple[Path, int]:
    if not INHIBITOR_DOCK.is_file():
        raise SystemExit(f"Missing docking JSON: {INHIBITOR_DOCK}")
    dj = json.loads(INHIBITOR_DOCK.read_text(encoding="utf-8"))
    results = sorted(
        dj.get("results", []),
        key=lambda r: float(r.get("best_affinity_kcal_mol", 0.0)),
    )
    if not results:
        raise SystemExit(f"No docking results in {INHIBITOR_DOCK}")
    table_rows: list[list[str]] = []
    for r in results:
        smi = r.get("smiles", "")
        table_rows.append(
            [
                DOCKING_LABEL_SHORT.get(smi, smi[:24] + "…"),
                smi,
                f"{float(r['best_affinity_kcal_mol']):.3f}",
                str(r.get("n_poses", "")),
            ]
        )
    body = md_table(["Compound", "SMILES", "Best Vina (kcal mol⁻¹)", "Poses"], table_rows)
    out = OUT / "INHIBITOR_TABLE1.md"
    out.write_text(
        "<!-- Generated by generate_manuscript_tables.py from docking_autodock_vina_results.json — do not edit by hand. -->\n\n"
        f"**Table 1.** Docking summary from `{INHIBITOR_DOCK.relative_to(ROOT)}` (chained run `032000Z`).\n\n"
        + body
        + "\n",
        encoding="utf-8",
    )
    return out, len(table_rows)


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    pa_path, pa_n = export_plan_a_table1()
    inh_path, inh_n = export_inhibitor_table1()
    meta = {
        "plan_a_table1": str(pa_path),
        "plan_a_table1_rows": pa_n,
        "plan_a_source": str(PLAN_A_TSV),
        "inhibitor_table1": str(inh_path),
        "inhibitor_table1_rows": inh_n,
        "inhibitor_source": str(INHIBITOR_DOCK),
        "policy": "All cells are copied from archived artifacts; no synthetic or placeholder values.",
    }
    (OUT / "table_metadata.json").write_text(json.dumps(meta, indent=2), encoding="utf-8")
    print(f"Wrote {pa_path} ({pa_n} rows)")
    print(f"Wrote {inh_path} ({inh_n} rows)")


if __name__ == "__main__":
    main()
