"""Source packaging only: no imports of project modules, no scientific computation."""
from pathlib import Path
import argparse, hashlib, json, tarfile, gzip, io
parser=argparse.ArgumentParser(description=__doc__)
parser.add_argument('source_root',type=Path,help='cyclic_llm source directory')
parser.add_argument('output_dir',type=Path,help='new bundle directory; must not exist')
args=parser.parse_args()
src=args.source_root.resolve(); out=args.output_dir.resolve()
if not src.is_dir():raise ValueError('source root must exist')
if out==src or src in out.parents:raise ValueError('bundle output must be outside source tree')
if out.with_suffix('.tar.gz').exists():raise ValueError('archive already exists')
out.mkdir(parents=True,exist_ok=False)
relative=[]
relative += [p.relative_to(src) for p in (src/'allatom_paper/hybrid').glob('*.py')]
relative += [Path('allatom_paper/hybrid/ec2/qa_integration.sh')]
for package,names in {
 'allatom_paper': ['contracts.py','pmo_harness.py','tier0_rules.py','test_orchestrator_ia.py','test_pmo_harness.py'],
 'allatom_paper/orchestrator':['__init__.py','loop.py','toy.py'],
 'allatom_paper/feedback':['__init__.py','preference_updater.py','stop_monitor.py','hack_env.py','toy_policy.py','test_preference_updater.py','test_stop_monitor.py'],
 'allatom_paper/retrieval':['__init__.py','store.py','index.py','retriever.py','blind.py','prompt.py','test_retrieval.py'],
 'allatom_paper/knowledge_scale':['config.py','verify.py','eligibility.py','test_k2.py','test_semantic_eligibility.py'],
 'allatom_paper/patent_mining':['config.py','gp_parse.py','pm_filter.py','seq2smiles.py','verify_patent.py','extract_patents.py','repair_sidecar.py','test_k4.py','test_sequence_repairs.py'],
 'ihlm_backbone':['__init__.py','pclm_encoder.py','pclm_tokenizer.py','NOTICE.md'],
}.items():
 relative.extend(Path(package)/name for name in names)
relative += [Path('pharmacophore_knowledge.py')]
relative=sorted(set(relative))
# Fail rather than silently retaining files from an unrelated previous bundle.
allowed={Path('cyclic_llm')/p for p in relative}|{Path('source_manifest.json'),Path('README.md')}
for existing in out.rglob('*'):
 if existing.is_file() and existing.relative_to(out) not in allowed:
  raise RuntimeError('unexpected existing bundle file: '+str(existing))
manifest=[]
for relative_path in relative:
 original=src/relative_path
 if original.is_symlink() or not original.is_file():raise RuntimeError('missing or symlinked source '+str(original))
 data=original.read_bytes()
 target=out/'cyclic_llm'/relative_path;target.parent.mkdir(parents=True,exist_ok=True)
 target.write_bytes(data)
 manifest.append(dict(path=str(target.relative_to(out)),bytes=len(data),sha256=hashlib.sha256(data).hexdigest()))
doc=dict(schema='method_synthetic_cpu_qa_sources_v1',purpose='Source-only synthetic CPU integration QA, not a scientific study or real-model validation',
         source_root='research/guangzhou_all_atom/cyclic_llm',files=manifest,
         fixtures='All JSON/tensor fixtures are generated by tests in temporary directories on the approved EC2 host; none bundled.',
         excluded=['raw datasets','research model weights','credentials','git history','research result files'])
(out/'source_manifest.json').write_text(json.dumps(doc,indent=2,sort_keys=True)+'\n')
(out/'README.md').write_text('''# Source-only method integration QA bundle

This snapshot preserves the selected `cyclic_llm` package layout. It contains the synthetic QA tests and their source dependencies, not the complete research runtime. In particular, `hybrid/run_stage1.py` is included for finalisation helper tests, not for executing a scientific study from this bundle.

The source manifest lists every copied source file with byte length and SHA-256. There are no raw datasets, pretrained weights, secrets, Git metadata or result files. Tests generate their own temporary JSON and tensor fixtures. Literature semantic-review and patent sequence-repair tests run in separate processes to isolate their legacy top-level imports. The pharmacophore source module is included because retrieval prompt tests dynamically import it; no corpus files accompany it.

No tests were run while packaging. Test execution requires separately approved EC2 Spot CPU compute. The runner checks EC2 Spot metadata before installation and has a 1,200-second timeout; the launch wrapper must provide independent shutdown, cost controls and artifact upload.

After extracting into a remote directory, the launch wrapper invokes:

    bash cyclic_llm/allatom_paper/hybrid/ec2/qa_integration.sh "$PWD/cyclic_llm" /absolute/new-output-directory

Host requirements: Linux x86_64 EC2 Spot; Bash, curl, GNU timeout, Python 3.11 with venv support; network access for Python dependency installation. The runner pins pip 25.1.1 and installs CPU Torch 2.6.0+cpu, Transformers 4.51.3, PEFT 0.15.2, Accelerate 1.6.0, NumPy 2.2.6, SciPy 1.15.3, RDKit 2025.3.2 and pytest 8.3.5. Safetensors/tokenizers and other transitive dependencies resolve through these packages; pip freeze and pip check are retained. This is a candidate environment, not an asserted tested lock.

After dependency installation, Hugging Face offline switches prevent model downloads. The runner requires zero failed, errored or skipped tests before writing done.flag. A synthetic pass cannot establish real ChemFM checkpoint quality, measured knowledge benefit, low-precision execution equivalence or study acceptance.
''')
archive=out.with_suffix('.tar.gz')
with archive.open('xb') as raw:
 with gzip.GzipFile(filename='',mode='wb',fileobj=raw,mtime=0) as gz:
  with tarfile.open(fileobj=gz,mode='w') as tar:
   for file in sorted(p for p in out.rglob('*') if p.is_file()):
    data=file.read_bytes();info=tarfile.TarInfo(str(file.relative_to(out)))
    info.size=len(data);info.mtime=0;info.uid=info.gid=0;info.uname=info.gname='';info.mode=0o644
    tar.addfile(info,io.BytesIO(data))
summary=dict(directory=str(out),archive=str(archive),source_files=len(manifest),archive_files=len(manifest)+2,
             archive_bytes=archive.stat().st_size,archive_sha256=hashlib.sha256(archive.read_bytes()).hexdigest(),
             manifest_sha256=hashlib.sha256((out/'source_manifest.json').read_bytes()).hexdigest())
print(json.dumps(summary,indent=2))
