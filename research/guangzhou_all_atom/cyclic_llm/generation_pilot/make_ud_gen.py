#!/usr/bin/env python3
"""EC2 user-data generator for pilot 3 (docs/20261031_GENERATION_PILOT3_PREREG.md). Spot CPU only; resumable (finished generators are skipped); dev -> upload -> WAIT for the committed frozen config on S3 -> test.
No bare `wait`: each generator process is waited for by PID; the sync loop is killed explicitly. usage: make_ud_gen.py a|b OUT.sh [--cap-min 240]"""
import sys, argparse
B = "s3://biomate-nextflow-work/cyclic_peptide/gen_pilot3"
CPU_GROUPS = [["S-EDIT"], ["S-LIB", "C-COPY"], ["S-BRICS"], ["L-P0"], ["L-PCLM2"], ["C-RANDINIT-P0", "C-RANDINIT-PCLM2", "C-SHUF-PCLM2"]]
HEAD = """#!/bin/bash
# pilot 3 generation job, set __SET__; generated by make_ud_gen.py
B=__B__
exec > /var/log/ud.log 2>&1; set -x
shutdown -h +__CAP__
( while true; do aws s3 cp /var/log/ud.log $B/logs/ud___SET__.log --only-show-errors; sleep 20; done ) &
BOOTSYNC=$!
dnf install -y python3.11 python3.11-pip python3.11-devel gcc >/dev/null 2>&1
python3.11 -m pip install numpy scipy scikit-learn rdkit 2>&1 | tail -2
python3.11 -m pip install "torch==2.13.0+cpu" --extra-index-url https://download.pytorch.org/whl/cpu 2>&1 | tail -3
python3.11 -m pip install transformers safetensors 2>&1 | tail -2
mkdir -p /w/out /w/data /w/code && cd /w
aws s3 cp $B/code.tgz /w/code.tgz --only-show-errors && tar xzf /w/code.tgz -C /w/code
aws s3 cp s3://biomate-nextflow-work/cyclic_peptide/loop_retro/data/CycPeptMPDB_Peptide_All.csv /w/data/ --only-show-errors
aws s3 sync $B/out___SET__/ /w/out/ --only-show-errors
export CPM_CSV=/w/data/CycPeptMPDB_Peptide_All.csv PYTHONHASHSEED=0
G=/w/code/cyclic_llm/generation_pilot
( while true; do aws s3 sync /w/out $B/out___SET__/ --only-show-errors; sleep 30; done ) &
SYNC=$!
"""
CPU_BODY = """aws s3 cp s3://biomate-nextflow-work/cyclic_peptide/allatom/pretrain/ckpt.pt /w/p0_ckpt.pt --only-show-errors
aws s3 cp s3://biomate-nextflow-work/cyclic_peptide/allatom/pretrain/vocab.json /w/p0_vocab.json --only-show-errors
python3.11 /w/code/cyclic_llm/ihlm_backbone/fetch_weights.py small /w/pclm2 > /w/fetch.log 2>&1; cat /w/fetch.log
export P0_CKPT=/w/p0_ckpt.pt P0_VOCAB=/w/p0_vocab.json PCLM2_DIR=/w/pclm2/small
python3.11 $G/gen_pilot.py selftest > /w/selftest.log 2>&1; echo "selftest rc=$?" >> /w/selftest.log; aws s3 cp /w/selftest.log $B/logs/selftest___SET__.log --only-show-errors
PIDS=()
__PROCS__
for p in "${PIDS[@]}"; do wait $p; done
"""
CHEMFM_BODY = """mkdir -p /w/chemfm && cd /w/chemfm
SHA=__SHA__
for f in config.json generation_config.json special_tokens_map.json tokenizer.json tokenizer_config.json model.safetensors; do curl -sL -o $f https://huggingface.co/ChemFM/ChemFM-1B/resolve/$SHA/$f; done
echo "24686705d779db6876acc09c81d64d432262ef8b5dbfccc385212587079ce419  model.safetensors" | sha256sum -c - || { echo CHEMFM_SHA_MISMATCH; aws s3 cp /var/log/ud.log $B/logs/FAILED___SET__.log --only-show-errors; shutdown -h now; exit 3; }
cd /w; export CHEMFM_DIR=/w/chemfm OMP_NUM_THREADS=32
( python3.11 $G/gen_pilot.py dev /w/out --gens L-CHEMFM --n-dev 300 > /w/dev_chemfm.log 2>&1; aws s3 cp /w/dev_chemfm.log $B/logs/dev_chemfm.log --only-show-errors
  until aws s3 cp $B/frozen___SET__.json /w/frozen.json --only-show-errors; do sleep 30; done
  python3.11 $G/gen_pilot.py test /w/out --gens L-CHEMFM --cfg /w/frozen.json > /w/test_chemfm.log 2>&1; aws s3 cp /w/test_chemfm.log $B/logs/test_chemfm.log --only-show-errors ) &
PIDS=($!)
for p in "${PIDS[@]}"; do wait $p; done
"""
TAIL = """aws s3 sync /w/out $B/out___SET__/ --only-show-errors
echo DONE > /w/done.flag; aws s3 cp /w/done.flag $B/flags/done___SET__.flag --only-show-errors
kill $SYNC $BOOTSYNC; aws s3 cp /var/log/ud.log $B/logs/ud___SET___final.log --only-show-errors; shutdown -h now
"""


def proc(gens):
    dev = ",".join(g for g in gens if not g.startswith(("C-",)))
    allg = ",".join(gens)
    lines = []
    if dev: lines.append(f"python3.11 $G/gen_pilot.py dev /w/out --gens {dev} --n-dev 300 > /w/dev_{gens[0]}.log 2>&1")
    lines.append(f"aws s3 cp /w/dev_{gens[0]}.log $B/logs/ --only-show-errors 2>/dev/null")
    lines.append("until aws s3 cp $B/frozen___SET__.json /w/frozen.json --only-show-errors; do sleep 30; done")
    lines.append(f"python3.11 $G/gen_pilot.py test /w/out --gens {allg} --cfg /w/frozen.json > /w/test_{gens[0]}.log 2>&1")
    lines.append(f"aws s3 cp /w/test_{gens[0]}.log $B/logs/ --only-show-errors")
    return "( " + "; ".join(lines) + " ) &\nPIDS+=($!)"


if __name__ == "__main__":
    ap = argparse.ArgumentParser(); ap.add_argument("set"); ap.add_argument("out"); ap.add_argument("--cap-min", type=int, default=240); ap.add_argument("--chemfm-sha", default=""); a = ap.parse_args()
    if a.set == "a": body = CPU_BODY.replace("__PROCS__", "\n".join("OMP_NUM_THREADS=4 " + proc(g) if False else proc(g) for g in CPU_GROUPS))
    else: body = CHEMFM_BODY.replace("__SHA__", a.chemfm_sha)
    s = (HEAD + ("export OMP_NUM_THREADS=4\n" if a.set == "a" else "") + body + TAIL).replace("__B__", B).replace("__SET__", a.set).replace("__CAP__", str(a.cap_min)); open(a.out, "w").write(s); print("wrote", a.out)
