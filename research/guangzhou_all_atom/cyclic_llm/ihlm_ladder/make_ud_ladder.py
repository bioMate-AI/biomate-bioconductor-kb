#!/usr/bin/env python3
"""Generate the EC2 user-data script for the IH-LM ladder run (docs/20261030_IHLM_LADDER_PREREG.md + A2). Spot-safe: every arm of every task is written to a per-task JSON and synced to S3 every 45 s; the whole job is resumable
(restart = relaunch the same script; finished arms are skipped); self-terminating (hard wall-clock cap + shutdown at the end). NEVER a bare `wait`: units run under `xargs -P` in the foreground; the sync loop is the only background job and is killed explicitly.
usage: make_ud_ladder.py OUT.sh [--procs 30] [--cap-min 200] [--stage all|primary]"""
import sys, argparse
B = "s3://biomate-nextflow-work/cyclic_peptide/ihlm_ladder"
LADDER = "R0,R1,R2,R3,R4"
PRIMARY_ARMS = "R0,R1,R2,R3,R4,R1_kshuf,R4_shuf,R4_frozen,gbm_aware,knn,gp,random_fb,rule_kphys"


def units(stage):
    if stage == "confirm":                                            # prereg section 5: confirmatory seeds 10-19, primary design only (zc, k = 5, all 13 arms), configuration frozen
        return [(reg, seed, "zc", 5, PRIMARY_ARMS) for reg in "ABL" for seed in range(10, 20)]
    u = []                                                            # (regimes, seeds, scheme, k, arms), longest first
    for reg in "ABL":
        for seed in range(10): u.append((reg, seed, "zc", 5, PRIMARY_ARMS))                  # primary: causal labels, k = 5, development seeds 0-9
    if stage == "all":
        for reg in "ABL":
            for seed in range(5): u.append((reg, seed, "zt", 5, LADDER + ",gbm_aware"))      # A2: transductive-label control, all five rungs
        for reg in "AL":
            for seed in range(5): u.append((reg, seed, "gc", 5, LADDER))                     # secondary scheme (global-centred causal labels; source offsets present) on 5 seeds in A and L
        for k in (0, 10):
            for reg in "ABL":
                for seed in range(5): u.append((reg, seed, "zc", k, "R1,R2"))                # anchor-count sensitivity, R1 vs R2 only
    return u


HEAD = """#!/bin/bash
# IH-LM ladder (R0-R4) spot job; resumable; per-arm results synced to S3 every 45 s; self-terminating. Generated by make_ud_ladder.py
B=__B__
TAG=__TAG__
exec > /var/log/ud.log 2>&1; set -x                   # everything this script does is logged and shipped to S3 from the first second (a silent early exit hid the cause of the first launch)
shutdown -h +__CAP__       # hard wall-clock cap
( while true; do aws s3 cp /var/log/ud.log $B/logs/ud_boot$TAG.log --only-show-errors; sleep 20; done ) &
BOOTSYNC=$!
dnf install -y python3.11 python3.11-pip python3.11-devel gcc >/dev/null 2>&1
python3.11 -m pip install numpy scipy scikit-learn rdkit 2>&1 | tail -2
python3.11 -m pip install "torch==2.13.0+cpu" --extra-index-url https://download.pytorch.org/whl/cpu 2>&1 | tail -3      # same torch as the local test run; PyPI stays the main index (the CPU index alone lacks torch's dependencies, which made the first attempt fail); output kept in the boot log
mkdir -p /w/data /w/o /w/code /w/logs && cd /w
aws s3 cp $B/code/ /w/code/ --recursive --exclude "*.pyc" --only-show-errors
aws s3 cp s3://biomate-nextflow-work/cyclic_peptide/loop_retro/data/CycPeptMPDB_Peptide_All.csv /w/data/ --only-show-errors
aws s3 sync $B/res/ /w/o/ --only-show-errors
export LABEL_COL=PAMPA SCRATCH=/w/data FP_CHIRAL=1 OMP_NUM_THREADS=1 PYTHONHASHSEED=0
cd /w/code/ihlm_ladder
{ python3.11 -c "import torch,numpy,scipy,sklearn,rdkit;print('torch',torch.__version__)"; echo "import rc=$?"; python3.11 test_ladder.py core; } > /w/pre.log 2>&1
sha256sum /w/code/ihlm/model.py /w/code/ihlm_ladder/*.py >> /w/pre.log
aws s3 cp /w/pre.log $B/preflight$TAG.log --only-show-errors
if ! grep -q "import rc=0" /w/pre.log || ! grep -q "core rc=0" /w/pre.log; then aws s3 cp /w/pre.log $B/PREFLIGHT_FAILED$TAG.log --only-show-errors; aws s3 cp /var/log/ud.log $B/logs/ud_boot$TAG.log --only-show-errors; shutdown -h +15; exit 3; fi
( while true; do aws s3 sync /w/o $B/res/ --only-show-errors --exclude "*.tmp"; aws s3 sync /w/logs $B/logs/ --only-show-errors; sleep 45; done ) &
SYNC=$!
cat > /w/units.txt <<'UNITS'
__UNITS__
UNITS
run_unit(){ set -- $1; python3.11 -u run_ladder.py /w/data/CycPeptMPDB_Peptide_All.csv /w/o --regimes $1 --seeds $2 --scheme $3 --k-anchor $4 --arms $5 > /w/logs/u_$1_$2_$3_k$4.log 2>&1; }
export -f run_unit
cat /w/units.txt | xargs -P __PROCS__ -I{} bash -c 'run_unit "{}"'
aws s3 sync /w/o $B/res/ --only-show-errors --exclude "*.tmp"; aws s3 sync /w/logs $B/logs/ --only-show-errors
echo DONE > /w/done.flag; aws s3 cp /w/done.flag $B/done$TAG.flag --only-show-errors
kill $SYNC $BOOTSYNC; aws s3 cp /var/log/ud.log $B/logs/ud_boot$TAG.log --only-show-errors; shutdown -h now
"""

if __name__ == "__main__":
    ap = argparse.ArgumentParser(); ap.add_argument("out"); ap.add_argument("--procs", type=int, default=30); ap.add_argument("--cap-min", type=int, default=200); ap.add_argument("--stage", default="all"); a = ap.parse_args()
    us = units(a.stage); lines = "\n".join(f"{r} {s} {sc} {k} {arms}" for r, s, sc, k, arms in us)
    open(a.out, "w").write(HEAD.replace("__B__", B).replace("__CAP__", str(a.cap_min)).replace("__PROCS__", str(a.procs)).replace("__TAG__", "" if a.stage != "confirm" else "_confirm").replace("__UNITS__", lines)); print("wrote", a.out, "units", len(us))
