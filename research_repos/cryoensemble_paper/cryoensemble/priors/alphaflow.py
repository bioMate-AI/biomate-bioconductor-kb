"""AlphaflowPrior — wraps Jing et al.'s AlphaFlow as a PriorAdapter.

Reference
---------
Bowen Jing, Bonnie Berger, Tommi Jaakkola, "AlphaFold Meets Flow Matching for
Generating Protein Ensembles", arXiv:2402.04845 / ICML 2024.

Why AlphaFlow is well-suited for DPS
------------------------------------
At each integrator step AlphaFlow's neural model predicts the *endpoint*
x_0 given the noisy current state x_t:

    output = self.model(batch_with_x_t_conditioning)
    pseudo_beta = pseudo_beta_fn(output)   # ≈ E[x_0 | x_t]

The flow integrator linearly interpolates the noisy state toward the predicted
endpoint:

    x_{t-1} = (s/t) · x_t + (1 - s/t) · E[x_0 | x_t]

Tweedie's formula says the conditional mean E[x_0 | x_t] is exactly the
denoised mean of x_t, and the score is

    ∇_{x_t} log p_t(x_t) = (E[x_0 | x_t] - x_t) / σ_t²

so AlphaFlow's *single forward pass* gives us the score directly — no Monte
Carlo estimate, no sampler-only Tweedie wrapper.

Implementation notes
--------------------
Heavy AlphaFlow dependencies (openfold custom kernels, torch 1.13.1+cu117) are
**not available on the local GB10 / CUDA 13 machine**. The actual model is run
inside the AlphaFlow container on AWS Batch and the resulting conformer pool
is loaded back into this adapter. For DPS this adapter therefore operates in
TWO MODES:

  • "cached" mode  → conformer pool was pre-generated by `predict.py` in the
                     AlphaFlow container; sample() returns from this pool;
                     score() falls back to the kernel-smoothed approximation
                     of DeltaEnsemblePrior. Equivalent to per-particle EM
                     mixture but with a much richer ensemble than 1 PDB +
                     perturbations.
  • "online" mode  → ONLY usable inside the AlphaFlow container; calls
                     `inference()` directly and exposes the Tweedie-exact
                     score per DPS step. NotImplementedError when invoked
                     outside the container.

The cached path is the right choice for end-to-end research-grade runs:
- Run AlphaFlow once per protein on AWS (generate N conformers, ~minutes/sample)
- Run CryoEnsemble locally with the cached prior + GB10 GPU for likelihood
- Iterate quickly without re-running the heavy generator

The online path is the right choice for a future "tight DPS loop" once the
GB10 environment is properly set up or the inference is moved to AWS.
"""

from __future__ import annotations

import tarfile
from pathlib import Path
from typing import Optional

import torch

from .base import PriorAdapter, PriorMetadata
from .delta import DeltaEnsemblePrior


# ──────────────────────────────────────────────────────────────────────────────
# Cached-mode adapter
# ──────────────────────────────────────────────────────────────────────────────

class AlphaflowPrior(PriorAdapter):
    """Cached-mode AlphaFlow prior: load a pre-generated ensemble from disk."""

    def __init__(
        self,
        conformer_pool: torch.Tensor,
        *,
        model_version: str = "alphaflow-md-templates-12l-distilled-202406",
        n_samples_generated: int | None = None,
        kernel_sigma: float = 0.3,
    ):
        """
        Parameters
        ----------
        conformer_pool : (N, n_atoms, 3) Cα coords from AlphaFlow inference.
        model_version  : provenance string (logged to outputs).
        n_samples_generated : original ensemble size if conformer_pool is a subsample.
        kernel_sigma   : smooth-score bandwidth for DPS gradient flows.
        """
        if conformer_pool.ndim != 3 or conformer_pool.shape[-1] != 3:
            raise ValueError(f"conformer_pool must be (N, A, 3); got {tuple(conformer_pool.shape)}")
        self.conformer_pool = conformer_pool - conformer_pool.mean(dim=1, keepdim=True)
        self.model_version = model_version
        self._n_total = n_samples_generated if n_samples_generated is not None else conformer_pool.shape[0]
        self.kernel_sigma = float(kernel_sigma)
        # The actual score machinery is the smooth-kernel KDE inherited via composition
        self._kde = DeltaEnsemblePrior(self.conformer_pool, kernel_sigma=kernel_sigma,
                                       name="alphaflow_kde",
                                       trained_on="AlphaFlow-MD+Templates samples")

    # ── PriorAdapter interface ─────────────────────────────────────────────────

    def metadata(self) -> PriorMetadata:
        return PriorMetadata(
            name="alphaflow",
            kind="flow",
            n_atoms=int(self.conformer_pool.shape[1]),
            trained_on="MD@300K + PDB templates",
            notes=f"model={self.model_version}; pool_size={self._n_total}",
        )

    def sample(self, n: int, **kwargs) -> torch.Tensor:
        idx = torch.randint(0, self.conformer_pool.shape[0], (n,))
        return self.conformer_pool[idx].clone()

    def score(self, x: torch.Tensor, t=None, **kwargs) -> torch.Tensor:
        """Score from a kernel-density estimate over the AlphaFlow conformer pool.

        For the *true Tweedie score* we'd need access to the AlphaFlow neural
        denoiser, which is only available in the AlphaFlow container. This
        cached-mode score is an approximation appropriate for an external prior:
        the cached pool is treated as the prior's mode coverage, and the score
        attracts coordinates toward the closest pool member with kernel-σ
        smoothing.
        """
        return self._kde.score(x, t=t, **kwargs)


# ──────────────────────────────────────────────────────────────────────────────
# Loaders for AlphaFlow output formats
# ──────────────────────────────────────────────────────────────────────────────

def load_alphaflow_pool_from_outpdb(
    outpdb_dir: str | Path,
    *,
    chain: str = "A",
    n_max: int | None = None,
) -> torch.Tensor:
    """Load all PDBs from an AlphaFlow `--outpdb` directory into one tensor.

    AlphaFlow `predict.py` writes one multi-model PDB per protein under
    `outpdb/<protein_id>.pdb`. Each MODEL block is one conformer.
    """
    outpdb_dir = Path(outpdb_dir)
    files = sorted(outpdb_dir.glob("*.pdb"))
    if not files:
        raise FileNotFoundError(f"No .pdb in {outpdb_dir}")

    coords_list: list[list[list[float]]] = []
    for pdb in files:
        cur_model: list[list[float]] = []
        seen = set()
        with open(pdb) as fh:
            for line in fh:
                if line.startswith("MODEL"):
                    cur_model = []
                    seen = set()
                elif line.startswith("ATOM"):
                    if line[12:16].strip() != "CA":
                        continue
                    if line[21] != chain:
                        continue
                    rn = int(line[22:26])
                    if rn in seen:
                        continue
                    seen.add(rn)
                    cur_model.append([
                        float(line[30:38]), float(line[38:46]), float(line[46:54])
                    ])
                elif line.startswith("ENDMDL"):
                    if cur_model:
                        coords_list.append(cur_model)
                    cur_model = []
            # Single-model PDBs may not have ENDMDL
            if cur_model:
                coords_list.append(cur_model)
        if n_max is not None and len(coords_list) >= n_max:
            break

    if n_max is not None:
        coords_list = coords_list[:n_max]
    n = min(len(c) for c in coords_list)
    arr = torch.tensor([c[:n] for c in coords_list], dtype=torch.float32)
    return arr


def load_alphaflow_pool_from_tarball(tarball: str | Path, *, chain: str = "A", n_max: int | None = None) -> torch.Tensor:
    """Load conformer pool from a tarball of PDB files (one PDB per conformer)."""
    coords_list: list[list[list[float]]] = []
    with tarfile.open(tarball) as tf:
        members = sorted([m for m in tf.getmembers() if m.name.endswith(".pdb")], key=lambda m: m.name)
        if n_max:
            members = members[:n_max]
        for m in members:
            fh = tf.extractfile(m)
            if fh is None:
                continue
            ca = []
            seen = set()
            for line in fh.read().decode().splitlines():
                if line.startswith("ATOM") and line[12:16].strip() == "CA" and line[21] == chain:
                    rn = int(line[22:26])
                    if rn in seen:
                        continue
                    seen.add(rn)
                    ca.append([float(line[30:38]), float(line[38:46]), float(line[46:54])])
            if ca:
                coords_list.append(ca)
    n = min(len(c) for c in coords_list)
    arr = torch.tensor([c[:n] for c in coords_list], dtype=torch.float32)
    return arr


