#!/usr/bin/env python3
"""Static audit of the curated workflow chains (table workflow_chains in backend/database/galaxy_ai_tools.db). Read-only, no execution.

  python3 scripts/audit_workflow_chains.py [--markdown FILE]

Checks, per chain: (1) does every step resolve to an executable workflow (same cascade as workflow_chain.resolve_workflow_name_to_path);
(2) for each connection, is ``to_input`` a parameter the downstream workflow actually declares (regex ``params.X`` in main.nf plus
nextflow_schema.json). (2) matters because workflow_chain._apply_connection_handoffs injects the upstream artifact as params[to_input];
type-based mapping is used only for chains WITHOUT connections. 'unknown' = downstream file missing or params declared elsewhere.
"""
import argparse, json, os, re, sqlite3, sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "backend")
DB = os.path.join(ROOT, "database", "galaxy_ai_tools.db")
WF = os.path.join(ROOT, "biomni_workflows")
c = sqlite3.connect("file:%s?mode=ro" % DB, uri=True)


def resolve(name, wid):
    if wid is not None:
        r = c.execute("SELECT filename FROM workflows WHERE id=? AND executable=1 LIMIT 1", (int(wid),)).fetchone()
        if r and r[0]:
            return r[0]
    if not name:
        return None
    name = name.strip(); bare = re.sub(r"^bioc[_-]", "", name, flags=re.I).strip()
    slug = name.lower().replace(" ", "_").replace("-", "_"); bs = bare.lower().replace(" ", "_").replace("-", "_")
    for w, p in [("lower(name)=lower(?)", name), ("lower(name)=lower(?)", bare), ("name LIKE ?", "%" + name + "%"),
                 ("replace(lower(name),' ','')=replace(lower(?),' ','')", name), ("lower(filename) LIKE ?", "%/" + bs + "/%"),
                 ("lower(filename) LIKE ?", "%" + slug + "%"), ("lower(filename) LIKE ?", "%" + name.lower() + "%")]:
        r = c.execute("SELECT filename FROM workflows WHERE %s AND executable=1 LIMIT 1" % w, (p,)).fetchone()
        if r and r[0]:
            return r[0]
    return None


def declared_params(fn):
    p = os.path.join(WF, fn)
    if not os.path.exists(p):
        return None
    ps = set(re.findall(r"params\.([A-Za-z_][A-Za-z0-9_]*)", open(p, errors="ignore").read()))
    sch = os.path.join(os.path.dirname(p), "nextflow_schema.json")
    if os.path.exists(sch):
        try:
            j = json.load(open(sch))
            ps |= set(j.get("properties", {})) | {k for d in j.get("definitions", {}).values() for k in d.get("properties", {})}
        except Exception:
            pass
    return ps


def main():
    ap = argparse.ArgumentParser(); ap.add_argument("--markdown"); a = ap.parse_args()
    rows = c.execute("select name,domain,source,usage_count,steps,connections from workflow_chains order by domain,name").fetchall()
    unresolved, mism, tot = [], {}, {"ok": 0, "mismatch": 0, "unknown": 0}
    for n, dom, src, uc, steps, conns in rows:
        st = json.loads(steps); paths = [resolve(s.get("workflow_name"), s.get("workflow_id")) for s in st]
        miss = [s.get("workflow_name") for s, p in zip(st, paths) if not p]
        if miss:
            unresolved.append((n, len(st), miss))
        for cn in json.loads(conns or "[]"):
            d = int(cn["to_step"]) - 1; fn = paths[d] if 0 <= d < len(paths) else None
            ps = declared_params(fn) if fn else None
            k = "unknown" if ps is None else ("ok" if cn["to_input"] in ps else "mismatch")
            tot[k] += 1
            if k == "mismatch":
                mism.setdefault(n, []).append("%s (step %s)" % (cn["to_input"], cn["to_step"]))
    out = ["# Workflow chain audit (static, read-only)", "",
           "Generated by `scripts/audit_workflow_chains.py` from `workflow_chains` in `galaxy_ai_tools.db`.", "",
           "- chains: %d; total recorded runs (sum of usage_count): %d" % (len(rows), sum(r[3] or 0 for r in rows)),
           "- chains where every step resolves to an executable workflow: %d of %d" % (len(rows) - len(unresolved), len(rows)),
           "- connections: %d; `to_input` is a declared downstream parameter: %d; not declared (mismatch): %d; undeterminable: %d" % (sum(tot.values()), tot["ok"], tot["mismatch"], tot["unknown"]),
           "- chains with at least one mismatching connection: %d" % len(mism), "", "## Chains with unresolved steps", ""]
    out += ["- `%s` (%d steps): %s" % (n, L, ", ".join(sorted(set(m)))) for n, L, m in sorted(unresolved, key=lambda x: -x[1])]
    out += ["", "## Chains with connections whose `to_input` is not a declared parameter", ""]
    out += ["- `%s`: %s" % (n, "; ".join(v[:6])) for n, v in sorted(mism.items())]
    text = "\n".join(out) + "\n"
    print(text)
    if a.markdown:
        open(a.markdown, "w").write(text)


if __name__ == "__main__":
    sys.exit(main())
