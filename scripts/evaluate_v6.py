"""
v6 evaluation: run all 5 deterministic checkers on the v6 test split
generated by a trained adapter.

For each test example:
  1. Generate completion with the v6 adapter
  2. Route to the appropriate checker based on meta.task
  3. Record pass/fail per checker

Outputs:
  - JSONL with per-example {prompt, generated, expected, checker_result}
  - Aggregate metrics table per task

Usage:
    python scripts/evaluate_v6.py --adapter models/regulatory_llm_v6/lora_adapter
"""
from __future__ import annotations

import argparse
import json
import sys
from collections import defaultdict
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend" / "lib"))

from galaxy.ai.drug_discovery.adversity_language import detect_adversity
from galaxy.ai.drug_discovery.mrsd_verifier import verify_mrsd
from galaxy.ai.drug_discovery.phase_gating import required_studies, verify_phase_gating
from galaxy.ai.drug_discovery.structural_validator import (
    REQUIRED_SUBSECTIONS, validate_structure,
)
from galaxy.ai.drug_discovery.tabulated_summary import verify_table

DEFAULT_TEST = ROOT / "data/regulatory_training/tasks/splits_v6/test.jsonl"


def check_mrsd(generated: str, meta: dict) -> dict:
    r = verify_mrsd(generated)
    return {
        "passed": r.passed,
        "grounded": r.grounded,
        "issues": r.issues,
        "computed_hed": r.computed_hed_mg_per_kg,
        "computed_mrsd": r.computed_mrsd_mg_per_kg,
    }


def check_skeleton(generated: str, meta: dict) -> dict:
    sec = meta.get("section_id")
    if sec not in REQUIRED_SUBSECTIONS:
        return {"passed": False, "reason": f"no section_id for skeleton check"}
    r = validate_structure(generated, sec)
    return {
        "passed": r.passed,
        "missing": r.missing,
        "out_of_order": r.out_of_order,
    }


def check_phase_gating(generated: str, meta: dict) -> dict:
    req = required_studies(
        meta["phase"], meta["trial_duration_days"], meta["population"],
    )
    r = verify_phase_gating(generated, req)
    return {
        "passed": r.passed,
        "missing": r.missing,
        "found_count": len(r.found),
    }


def check_tabulated(generated: str, meta: dict) -> dict:
    tid = meta["template_id"]
    r = verify_table(generated, tid)
    return {
        "passed": r.passed,
        "missing_columns": r.missing_columns,
        "out_of_order": r.out_of_order,
        "n_data_rows": r.n_data_rows,
    }


def check_adversity(generated: str, meta: dict) -> dict:
    target = meta["adversity_category"]
    r = detect_adversity(generated)
    return {
        "passed": r.detected == target,
        "detected": r.detected,
        "target": target,
    }


CHECKERS = {
    "mrsd_computation":   check_mrsd,
    "skeleton_completion": check_skeleton,
    "phase_gating":       check_phase_gating,
    "tabulated_summary":  check_tabulated,
    "adversity_language": check_adversity,
}


def load_adapter(adapter_path: Path):
    """Load v6 model + tokenizer with the LoRA adapter."""
    import torch
    from peft import PeftModel
    from transformers import AutoModelForCausalLM, AutoTokenizer

    base_id = "Qwen/Qwen3-8B"
    print(f"Loading base model {base_id}...")
    tokenizer = AutoTokenizer.from_pretrained(base_id)
    model = AutoModelForCausalLM.from_pretrained(
        base_id, torch_dtype=torch.bfloat16, device_map="auto",
    )
    print(f"Attaching LoRA adapter from {adapter_path}...")
    model = PeftModel.from_pretrained(model, str(adapter_path))
    model.eval()
    return model, tokenizer


def generate(model, tokenizer, messages: list[dict], max_new_tokens: int = 1024) -> str:
    import torch
    text = tokenizer.apply_chat_template(
        messages[:-1],  # exclude the gold assistant turn
        tokenize=False, add_generation_prompt=True,
    )
    inputs = tokenizer(text, return_tensors="pt").to(model.device)
    with torch.no_grad():
        out = model.generate(
            **inputs,
            max_new_tokens=max_new_tokens,
            do_sample=False,
            temperature=1.0,
            pad_token_id=tokenizer.eos_token_id,
        )
    gen = tokenizer.decode(out[0][inputs.input_ids.shape[1]:], skip_special_tokens=True)
    return gen


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--adapter", type=Path, required=True)
    ap.add_argument("--test", type=Path, default=DEFAULT_TEST)
    ap.add_argument("--out", type=Path,
                    default=ROOT / "evaluation/results/regulatory_v6/test_predictions.jsonl")
    ap.add_argument("--limit", type=int, default=0, help="0 = all examples")
    args = ap.parse_args()

    args.out.parent.mkdir(parents=True, exist_ok=True)

    rows = [json.loads(l) for l in args.test.open()]
    if args.limit > 0:
        rows = rows[:args.limit]
    print(f"Evaluating on {len(rows)} test examples")

    model, tokenizer = load_adapter(args.adapter)

    per_task: dict[str, list[dict]] = defaultdict(list)
    with args.out.open("w") as f:
        for i, row in enumerate(rows):
            task = row.get("meta", {}).get("task")
            checker = CHECKERS.get(task)
            if checker is None:
                continue

            generated = generate(model, tokenizer, row["messages"])
            result = checker(generated, row["meta"])
            record = {
                "task": task,
                "meta": row["meta"],
                "expected": row["messages"][-1]["content"],
                "generated": generated,
                "checker_result": result,
            }
            f.write(json.dumps(record) + "\n")
            per_task[task].append(result)
            if (i + 1) % 25 == 0:
                print(f"  [{i+1}/{len(rows)}]")

    print("\n=== v6 per-task pass rates ===")
    summary: dict[str, Any] = {}
    for task, results in per_task.items():
        n_pass = sum(1 for r in results if r.get("passed"))
        rate = 100 * n_pass / max(len(results), 1)
        summary[task] = {"n": len(results), "passed": n_pass, "pass_rate": rate}
        print(f"  {task:25s} {n_pass:3d}/{len(results):3d}  ({rate:5.1f}%)")

    summary_path = args.out.parent / "summary.json"
    summary_path.write_text(json.dumps(summary, indent=2))
    print(f"\nSummary → {summary_path}")
    print(f"Predictions → {args.out}")


if __name__ == "__main__":
    main()
