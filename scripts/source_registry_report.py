#!/usr/bin/env python3
"""Print the data-source counts straight from the registry (the only numbers that should be quoted).

  PYTHONPATH=backend/lib python3 scripts/source_registry_report.py [--markdown FILE]

"Reachable from chat" means a live source on the federated-query surface (the research agent and chat fan-out) or one reached through
its own chat/MCP tool or agent (surface dedicated_tool: Open Targets via identify_targets, GEO via resolve_accession);
single-source, MCP-only and Galaxy-tool sources are listed separately.
"""
import argparse
import datetime
import sys

from galaxy.ai import data_sources as ds


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--markdown", help="also write the report to this file")
    a = ap.parse_args(argv)
    src = ds.SOURCES
    live = [s for s in src if s.status == "live"]
    chat = [s for s in live if ds.SURFACE_FEDERATION in s.surfaces or ds.SURFACE_DEDICATED in s.surfaces]
    queryable = [s for s in live if s.surfaces and s.surfaces != [ds.SURFACE_GALAXY_TOOL]]   # any non-Galaxy-import door
    single_only = [s for s in queryable if s not in chat]
    lines = ["# Data-source counts (generated %s)" % datetime.date.today().isoformat(), "",
             "Generated by `scripts/source_registry_report.py` from `backend/lib/galaxy/ai/data_sources.py`.", "",
             "| Measure | Count |", "|---|---|",
             "| Sources in the registry | %d |" % len(src), "| Live | %d |" % len(live),
             "| Planned | %d |" % len([s for s in src if s.status == "planned"]),
             "| Needs a key | %d |" % len([s for s in src if s.status == "key_required"]),
             "| Live and queryable by any door (fan-out, dedicated tool, single-source/MCP) | %d |" % len(queryable),
             "| of which: federated fan-out or dedicated tool | %d |" % len(chat),
             "| of which: single-source / MCP only (%s) | %d |" % (", ".join(sorted(x.name for x in single_only)), len(single_only)),
             "| Live Galaxy import tools only (not question-answering) | %d |" % len([x for x in live if x.surfaces == [ds.SURFACE_GALAXY_TOOL]])]
    for surf in (ds.SURFACE_FEDERATION, ds.SURFACE_DEDICATED, ds.SURFACE_SINGLE, ds.SURFACE_MCP, ds.SURFACE_GALAXY_TOOL):
        lines.append("| Live on surface `%s` | %d |" % (surf, len([s for s in live if surf in s.surfaces])))
    lines += ["", "## Live sources reachable from chat", ""] + ["- %s (%s)" % (s.name, s.category) for s in sorted(chat, key=lambda s: s.name.lower())]
    lines += ["", "## Live sources NOT reachable from chat", ""] + ["- %s (%s; surfaces: %s)" % (s.name, s.category, ", ".join(s.surfaces)) for s in sorted(live, key=lambda s: s.name.lower()) if s not in chat]
    out = "\n".join(lines) + "\n"
    print(out)
    if a.markdown:
        open(a.markdown, "w").write(out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
